def _record_stated(root: str, stated: dict, dry_run: bool = False) -> list:
    """Fill in whichever stated keys project.yml does not already carry.

    Only keys the caller actually passed on the command line: a default is
    not a statement, and writing `expects_data: measurements` into every
    project that never mentioned it would turn a silent default into a
    recorded decision nobody made.
    """
    out = []
    for key, value in stated.items():
        value = (value or "").strip()
        if not value:
            continue
        res = record_project_key(root, key, value, dry_run=dry_run)
        if res["action"] == "added":
            out.append(key)
    return out



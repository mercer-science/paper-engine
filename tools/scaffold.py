# The source text folder carries the round it holds - `drafts/source_text_r1`
# on a fresh project, renamed forward by `manuscript.py round`. The manifest
# above names the unlabelled folder because that is what the template
# directory is called; `source_text_dest` is what turns each of those entries
# into the folder this project actually uses.
#
# manuscript.py owns the same resolution in its LAYOUT CONTRACT block. This is
# a third copy rather than an import for the reason every engine here is
# standalone (spec 2.3), and `tests/scaffold.py` holds it against
# manuscript.py's.
SOURCE_TEXT_RE = re.compile(r"^source_text(?:_r(\d+))?$")
SOURCE_TEXT_MANIFEST = "drafts/source_text/"


def source_text_label(rnd: int) -> str:
    """The folder name for a given round; 0 means no round is known yet."""
    return "source_text_r%d" % rnd if rnd and rnd > 0 else "source_text"


def source_text_folders(d: str) -> list[tuple[int, str]]:
    """(round, name) for every source_text folder in `d`, oldest first."""
    out: list[tuple[int, str]] = []
    if not os.path.isdir(d):
        return out
    for name in os.listdir(d):
        m = SOURCE_TEXT_RE.match(name)
        if m and os.path.isdir(os.path.join(d, name)):
            out.append((int(m.group(1) or 0), name))
    return sorted(out)


def source_text_dest(root: str, dest: str, rnd: int = 1) -> str:
    """One manifest destination, pointed at this project's own folder.

    A project that already has one keeps it, whatever it is labelled: writing
    `source_text_r1/methods.md` into a project sitting at r8 would create a
    second folder that nothing builds from, which is the one failure this
    label was added to make visible rather than to cause.
    """
    if not dest.startswith(SOURCE_TEXT_MANIFEST):
        return dest
    found = source_text_folders(os.path.join(root, "drafts"))
    name = found[-1][1] if found else source_text_label(rnd)
    return "drafts/" + name + "/" + dest[len(SOURCE_TEXT_MANIFEST):]



def _r_str(s) -> str:
    """A Python string as an R string literal."""
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _mock_columns(bundle: dict) -> dict:
    """The first table in the bundle, its columns bucketed by kind."""
    files = bundle.get("data_files") or []
    if not files:
        return {}
    df = files[0]
    group = str(df.get("group_column") or "")
    out = {"file": str(df.get("file") or "measurements"), "group": group,
           "levels": [], "continuous": [], "count": [], "proportion": [],
           "categorical": [], "ordinal": []}
    for c in df.get("columns") or []:
        name, kind = str(c.get("name") or ""), str(c.get("kind") or "")
        if not name:
            continue
        if name == group:
            out["levels"] = [str(x) for x in (c.get("levels") or [])]
            continue
        if kind in out:
            out[kind].append(name)
    return out


# --- the two chart shapes ---------------------------------------------------
# Each returns the ggplot expression only, with no assignment and no trailing
# newline, so it can be dropped into a `p <- ...` or into a panel_title() call
# at whatever indent the caller needs.

def _expr_scatter(cols: dict, x: str, y: str, indent: str = "    ") -> str:
    g = cols["group"]
    colour = ", colour = %s, shape = %s" % (g, g) if g else ""
    legend = "%stheme_inside_legend() +\n" % indent if g else ""
    return ('ggplot(d, aes(x = %s, y = %s%s)) +\n'
            '%sgeom_point(size = 1.6) +\n'
            '%sgeom_smooth(method = "lm", formula = y ~ x, se = FALSE,\n'
            '%s            linewidth = 0.5) +\n'
            '%sannot_label(sprintf("n = %%d rows", nrow(d)), x = -Inf, hjust = 0) +\n'
            '%s'
            '%slabs(x = %s, y = %s, colour = NULL, shape = NULL)'
            % (x, y, colour, indent, indent, indent, indent, legend,
               indent, _r_str(x), _r_str(y)))


def _expr_by_group(cols: dict, col: str, indent: str = "    ") -> str:
    """A column against the grouping variable - or its distribution, when
    there is no grouping variable to put it against."""
    g = cols["group"]
    if g:
        return ('ggplot(d, aes(x = %s, y = %s, colour = %s)) +\n'
                '%sgeom_boxplot(outlier.shape = NA, linewidth = 0.4) +\n'
                '%sgeom_jitter(width = 0.15, size = 1.2, alpha = 0.8) +\n'
                '%sguides(colour = "none") +\n'
                '%slabs(x = NULL, y = %s)'
                % (g, col, g, indent, indent, indent, indent, _r_str(col)))
    return ('ggplot(d, aes(x = %s)) +\n'
            '%sgeom_histogram(bins = 12, fill = PALETTE[1], colour = "white") +\n'
            '%slabs(x = %s, y = "Count")' % (col, indent, indent, _r_str(col)))


def _by_group_detail(cols: dict) -> str:
    if cols.get("group"):
        return ("Each point is one synthetic row; box shows the median and "
                "interquartile range.")
    return "Distribution across the synthetic rows."


def mock_figure_specs(cols: dict) -> list[dict]:
    """Up to four figures, in the order they earn a slot.

    Figure 1 is a two-panel composite when the columns allow one, because the
    panel system is the part of the house style that has to be shown. The rest
    are one idea each and deliberately plain: they exist to prove the pipeline
    runs and that the columns are what the contract says. A figure that argues
    something is idea-generation's business.
    """
    g = cols.get("group") or ""
    cont = list(cols.get("continuous") or [])
    cnt = list(cols.get("count") or [])
    prop = list(cols.get("proportion") or [])
    where = "%s levels" % g if g else "samples"
    specs: list[dict] = []
    used: list[str] = []   # what the by-group slots below have taken

    # Figure 1 - the two-panel composite: a relationship beside a comparison.
    # This is the one that demonstrates panel_title(), the A/B tags, and the
    # patchwork operator, so it is built whenever there is a second column to
    # put in panel B.
    if len(cont) >= 2:
        x, y = cont[0], cont[1]
        panel_b = cnt[0] if cnt else (prop[0] if prop else
                                      (cont[2] if len(cont) > 2 else y))
        specs.append({
            "title": "%s against %s, and %s by %s" % (y, x, panel_b,
                                                      g or "sample"),
            "claim": "In the mock rows %s rises with %s, and %s separates "
                     "between %s." % (y, x, panel_b, where),
            "detail": "(A) Points are individual synthetic rows; line is an "
                      "ordinary least-squares fit. (B) %s"
                      % _by_group_detail(cols),
            "save_args": ", height = 2.6",
            "body": ("  p_a <- panel_title(\n"
                     "    %s,\n"
                     "    title = %s, tag = \"A\")\n"
                     "\n"
                     "  p_b <- panel_title(\n"
                     "    %s,\n"
                     "    title = %s, tag = \"B\")\n"
                     "\n"
                     "  # `|` puts panels side by side, `/` stacks them. Tags are set per\n"
                     "  # panel rather than by plot_annotation(tag_levels=), which would\n"
                     "  # recurse into a nested composite and burn extra letters.\n"
                     "  p <- p_a | p_b"
                     % (_expr_scatter(cols, x, y, indent="      "),
                        _r_str("%s against %s" % (y, x)),
                        _expr_by_group(cols, panel_b, indent="      "),
                        _r_str("%s by %s" % (panel_b, g or "sample"))))})
    # The remaining slots: one outcome column each, one slot each.
    #
    # A column already inside Figure 1 is NOT excluded here. Figure 1 shows two
    # columns against each other; these show one column against the groups,
    # which is a different view of the same data and the shape a results
    # section actually cites. Excluding them left two slots empty on a
    # four-column contract, which is the opposite of the point.
    #
    # The first continuous column is usually the independent variable
    # (temperature, dose, time), so it goes last rather than first: an outcome
    # by group is worth a slot before a setting by group is.
    ordered = cont[1:] + cnt + prop + cont[:1]
    for claim_tail in ("The primary outcome %s differs between %s.",
                       "%s shows the same separation between %s.",
                       "%s across %s, for comparison."):
        rest = [c for c in ordered if c not in used]
        if not rest:
            break
        c = rest[0]
        used.append(c)
        specs.append({
            "title": "%s by %s" % (c, g or "sample"),
            "claim": claim_tail % (c, where),
            "detail": _by_group_detail(cols),
            "save_args": "",
            "body": "  p <- %s" % _expr_by_group(cols, c, indent="    ")})

    return specs[:4]


def mock_table_specs(cols: dict) -> list[dict]:
    """Two tables: the summary every paper has, and the column inventory.

    The summary is the table a results section cites. The inventory is the one
    that catches a data contract disagreeing with the data - which is the most
    common way a float script fails.
    """
    g = cols.get("group") or ""
    if g:
        grp = "  grp <- list(%s = d[[%s]])" % (g, _r_str(g))
        label = _r_str(g)
    else:
        grp = '  grp <- list(Sample = rep("all", nrow(d)))'
        label = '"Sample"'
    summary_body = (
        "  num <- names(d)[vapply(d, is.numeric, logical(1))]\n"
        "%s\n"
        "  tab <- do.call(rbind, lapply(num, function(v) {\n"
        "    s <- stats::aggregate(d[[v]], by = grp,\n"
        "                          FUN = function(x)\n"
        '                            sprintf("%%.2f +/- %%.2f", mean(x), stats::sd(x)))\n'
        "    stats::setNames(data.frame(v, s[[1]], s$x, stringsAsFactors = FALSE),\n"
        '                    c("Measure", %s, "Mean +/- SD"))\n'
        "  }))" % (grp, label))
    inventory_body = (
        "  tab <- data.frame(\n"
        "    Column = names(d),\n"
        "    Type   = vapply(d, function(x) class(x)[1], character(1)),\n"
        "    Range  = vapply(d, function(x)\n"
        '               if (is.numeric(x)) sprintf("%.3g to %.3g", min(x), max(x))\n'
        '               else paste(sort(unique(as.character(x))), collapse = ", "),\n'
        "               character(1)),\n"
        "    stringsAsFactors = FALSE, row.names = NULL)")
    return [
        {"title": "Summary of the mock measurements",
         "claim": "Every numeric column, summarised by %s." % (g or "sample"),
         "detail": "Mean +/- SD across the synthetic rows.",
         "body": summary_body,
         "footer": 'sprintf("Synthetic rows from data/mock_data/; n = %d.", nrow(d))'},
        {"title": "Columns in the mock table",
         "claim": "The columns the data contract promises, as they arrive in R.",
         "detail": "Type and observed range of each column.",
         "body": inventory_body,
         "footer": '"Ranges are of the synthetic rows, not of any measurement."'},
    ]


def _caption_numbers(lines: list[str]) -> set:
    """(type, number) of every caption block already in the file.

    HTML comments are skipped: the scaffolded captions.md carries example
    headings inside its instruction comment, and those are not floats. The
    same rule read_captions.R applies, for the same reason.
    """
    out = set()
    in_comment = False
    for line in lines:
        if not in_comment and "<!--" in line:
            in_comment = "-->" not in line
            continue
        if in_comment:
            if "-->" in line:
                in_comment = False
            continue
        m = CAPTION_HEADING_EDIT_RE.match(line)
        if m:
            out.add((m.group(2).lower(), m.group(4).upper()))
    return out


def _caption_block(label: str, dirname: str, spec: dict) -> str:
    """One caption block, claim first, saying on its face that it is mock."""
    return ("## %s — %s\n**%s**\n%s *Built from mock data — replace it "
            "before this float means anything.*\n"
            % (label, dirname, spec["claim"], spec["detail"]))


def mock_floats(root: str, bundle: dict, force: bool = False,
                dry_run: bool = False) -> dict:
    """Fill the pre-made float slots with running scripts over the mock data.

    Only slots still holding the unbuilt template are filled: a script someone
    has already worked on is never touched, which is the never-overwrite rule
    the rest of this engine follows. `force` reclaims a slot whose script is
    itself a mock float, and still refuses to touch a real one.
    """
    res = {"path": os.path.abspath(root), "written": [], "skipped": [],
           "captions": [], "errors": [], "dry_run": dry_run}

    cols = _mock_columns(bundle)
    if not cols:
        res["errors"].append(
            "bundle has no data_files - nothing to build a float from. Run "
            "`idea.py mock` first, and pass it the same bundle.")
        return res
    if not (cols["continuous"] or cols["count"] or cols["proportion"]):
        res["errors"].append(
            "the bundle's first table has no continuous, count or proportion "
            "column, so there is nothing to plot. Check the `kind` on each "
            "column.")
        return res

    rel_csv = "data/mock_data/%s_mock.csv" % cols["file"]
    if not os.path.isfile(os.path.join(root, *rel_csv.split("/"))):
        res["errors"].append(
            "%s does not exist - run `idea.py mock` before building floats "
            "from it." % rel_csv)
        return res
    datafile = _r_str(rel_csv)

    existing = list_float_dirs(root)
    have_captions = _caption_numbers(_read_caption_lines(root))
    new_blocks: list[str] = []

    for kind, specs in (("figure", mock_figure_specs(cols)),
                        ("table", mock_table_specs(cols))):
        cfg = FLOAT_KINDS[kind]
        for n, spec in enumerate(specs, start=1):
            label = "%s %d" % (cfg["label"], n)
            hit = [f for f in existing
                   if f["kind"] == kind and f["number"] == str(n)]
            dirname = hit[0]["dir"] if hit else float_dir_name(kind, n)
            rel = "%s/%s/%s" % (cfg["dir"], dirname, cfg["script"])
            target = os.path.join(root, *rel.split("/"))

            if os.path.exists(target):
                with open(target, "r", encoding="utf-8") as fh:
                    body = fh.read()
                is_mock = MOCK_MARKER in body
                if "BUILT <- FALSE" not in body and not (is_mock and force):
                    res["skipped"].append(
                        {"path": rel, "label": label,
                         "why": "already a mock float; --force rebuilds it"
                                if is_mock
                                else "has been built - never overwritten"})
                    continue

            banner = MOCK_BANNER.format(marker=MOCK_MARKER, kind=kind)
            if kind == "figure":
                text = MOCK_FIGURE_TEMPLATE.format(
                    dirname=dirname, banner=banner, label=label,
                    title=spec["title"], datafile=datafile,
                    body=spec["body"], save_args=spec["save_args"])
            else:
                text = MOCK_TABLE_TEMPLATE.format(
                    dirname=dirname, banner=banner, label=label,
                    title=spec["title"], datafile=datafile, body=spec["body"],
                    footer=spec["footer"])

            res["written"].append({"path": rel, "label": label,
                                   "title": spec["title"]})
            if not dry_run:
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(target, "w", encoding="utf-8") as fh:
                    fh.write(text)

            if (cfg["label"].lower(), str(n)) not in have_captions:
                new_blocks.append(_caption_block(label, dirname, spec))
                res["captions"].append(label)

    if new_blocks and not dry_run:
        path = _captions_path(root)
        prior = ""
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as fh:
                prior = fh.read()
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(prior.rstrip("\n") + "\n\n" + "\n".join(new_blocks))
    return res


# ---------------------------------------------------------------------------
# Image-placeholder floats
# ---------------------------------------------------------------------------
# The imaging counterpart of the mock floats, and deliberately NOT built on
# mock data. A synthetic micrograph is not a thing this engine can make, and a
# fabricated one would be the worst file it could write. What it can do is
# build the figure STRUCTURE - the panel grid, the tags, the titles, the
# caption - with every panel a light grey box saying what image is expected in
# it. That renders, composes and prints; it just has no picture yet.
#
# So these carry no MOCK DATA watermark and create_floats.R does not refuse
# them, exactly as a `graphic_panel` figure whose art is still being drawn is
# not refused. Nothing here fabricates a measurement, so there is nothing for
# the mock containment to contain.

IMAGE_MARKER = "# --- image placeholder float (setup-project-directory) ---"

IMAGE_BANNER = """{marker}
# Written by `setup-project-directory` for a project whose evidence is
# pictures. Every panel below is a light grey placeholder carrying a
# description of the image that belongs in it: the figure renders now, and
# each panel fills itself in when you drop the .png into this folder under the
# filename named here.
#
# This float is NOT mock. Nothing about it is fabricated, so it carries no
# watermark and the co-author .docx will build it. A panel whose image has not
# arrived says so on its own face, in the figure, which is the honest version
# of "not collected yet".
#
# To finish a panel: save the image as this folder's <file>.png, then delete
# that panel's `describe =` argument. To change the layout, edit the patchwork
# expression - `refine-figure` does that with you."""

IMAGE_FIGURE_TEMPLATE = """# plan/figures/{dirname}/figure.R
{banner}

source(here::here("plan", "setup.R"))

# {label} - {title}

BUILT <- TRUE

if (BUILT) {{

{panels}
  p <- {layout}

  save_float(p, height = {height})

}} else {{
  message(float_key(), " not built yet - edit ",
          basename(float_dir()), "/figure.R")
}}
"""


def _image_layout(n: int) -> str:
    """The patchwork expression for n panels: one row up to two, then pairs.

    Two per row rather than three, because these are images and an image
    squeezed to a third of a double column is a thumbnail. `refine-figure`
    changes it; this only has to be a layout that reads.
    """
    names = ["p_%s" % chr(ord("a") + i) for i in range(n)]
    if n == 1:
        return names[0]
    if n == 2:
        return " | ".join(names)
    rows = []
    for i in range(0, n, 2):
        chunk = names[i:i + 2]
        rows.append("(%s)" % " | ".join(chunk) if len(chunk) > 1 else chunk[0])
    return " /\n       ".join(rows)


def _image_panel_spec(panel: dict, index: int) -> dict:
    """One panel of an image figure, defaulted from whatever the bundle gave.

    Everything but the description has a working default, because the
    description is the only part worth asking a human for: a panel named
    panelB.png with no sentence under it is exactly the uninformative grey box
    this command exists to replace.
    """
    tag = chr(ord("A") + index)
    file = str(panel.get("file") or "panel%s.png" % tag).strip()
    if not file.lower().endswith(".png"):
        file += ".png"
    return {"file": file,
            "title": str(panel.get("title") or "").strip(),
            "describe": str(panel.get("describe") or "").strip(),
            "aspect": panel.get("aspect"),
            "tag": tag,
            "var": "p_%s" % chr(ord("a") + index)}


def image_float_specs(bundle: dict) -> list[dict]:
    """The bundle's `figures` list, normalised. Raises nothing; reports."""
    out = []
    for i, fig in enumerate(bundle.get("figures") or [], start=1):
        panels = [_image_panel_spec(pn, j)
                  for j, pn in enumerate(fig.get("panels") or [])]
        if not panels:
            panels = [_image_panel_spec({}, 0)]
        out.append({
            "n": int(fig.get("n") or i),
            "title": str(fig.get("title") or "").strip() or "<one-line title>",
            "claim": str(fig.get("claim") or "").strip()
                     or "<the claim this figure makes, in one sentence>",
            "panels": panels,
        })
    return out


def _image_caption_block(label: str, dirname: str, spec: dict) -> str:
    """Claim first, then what each panel is waiting for.

    The per-panel sentence is the point: `writing-engine` reads captions.md,
    so writing down what panel B is expected to show means the paragraph that
    calls it out can be drafted before the image exists.
    """
    detail = []
    for pn in spec["panels"]:
        bit = pn["describe"] or ("image pending, %s" % pn["file"])
        head = "(%s)" % pn["tag"]
        if pn["title"]:
            head += " %s:" % pn["title"]
        detail.append("%s %s." % (head, bit.rstrip(".")))
    return ("## %s \u2014 %s\n**%s**\n%s\n*Panels are placeholders until the "
            "images land in `plan/figures/%s/`.*\n"
            % (label, dirname, spec["claim"], " ".join(detail), dirname))


def image_floats(root: str, bundle: dict, force: bool = False,
                 dry_run: bool = False) -> dict:
    """Fill figure slots with composed grey-panel placeholders.

    Same never-overwrite rule as `mock_floats`: only a slot still holding the
    unbuilt template is filled, and `force` reclaims one this command wrote
    while still refusing a real figure.
    """
    res = {"path": os.path.abspath(root), "written": [], "skipped": [],
           "captions": [], "undescribed": [], "errors": [], "dry_run": dry_run}

    specs = image_float_specs(bundle)
    if not specs:
        res["errors"].append(
            "bundle has no `figures` - nothing to lay out. Each entry needs a "
            "list of `panels`, and each panel a `describe` saying what image "
            "belongs in it.")
        return res

    res["undescribed"] = [{"label": "Figure %d" % sp["n"], "file": pn["file"]}
                          for sp in specs for pn in sp["panels"]
                          if not pn["describe"]]

    existing = list_float_dirs(root)
    have_captions = _caption_numbers(_read_caption_lines(root))
    new_blocks: list[str] = []
    cfg = FLOAT_KINDS["figure"]

    for spec in specs:
        n = spec["n"]
        label = "%s %d" % (cfg["label"], n)
        hit = [f for f in existing
               if f["kind"] == "figure" and f["number"] == str(n)]
        dirname = hit[0]["dir"] if hit else float_dir_name("figure", n)
        rel = "%s/%s/%s" % (cfg["dir"], dirname, cfg["script"])
        target = os.path.join(root, *rel.split("/"))

        if os.path.exists(target):
            with open(target, "r", encoding="utf-8") as fh:
                body = fh.read()
            is_ours = IMAGE_MARKER in body
            if BUILT_FALSE_RE.search(body) is None and not (is_ours and force):
                res["skipped"].append(
                    {"path": rel, "label": label,
                     "why": "already a placeholder float; --force rebuilds it"
                            if is_ours
                            else "has been built - never overwritten"})
                continue

        lines = []
        for pn in spec["panels"]:
            # graphic_panel(), never image_panel() with a title argument. An
            # aspect-locked panel ignores the height patchwork hands it, so a
            # title drawn INSIDE one floats over whatever sits beside it -
            # the failure graphic_panel()'s own comment records as
            # "Reaction sccAhpepmaeratus", and which this command reproduced
            # on its first render as "Sharpened FSCmap". The header/body
            # split cannot collide.
            args = [_r_str(pn["title"]) if pn["title"] else "NULL",
                    _r_str(pn["tag"])]
            if pn["describe"]:
                args.append("describe = %s" % _r_str(pn["describe"]))
            if pn["aspect"]:
                args.append("aspect = %s" % float(pn["aspect"]))
            pad = "\n" + " " * 23
            lines.append("  %s <- graphic_panel(%s,%s%s)"
                         % (pn["var"], _r_str(pn["file"]), pad,
                            ("," + pad).join(args)))
        n_panels = len(spec["panels"])
        text = IMAGE_FIGURE_TEMPLATE.format(
            dirname=dirname, banner=IMAGE_BANNER.format(marker=IMAGE_MARKER),
            label=label, title=spec["title"],
            panels="\n".join(lines) + "\n",
            layout=_image_layout(n_panels),
            height=("image_fig_height(%d, per_row = %d)"
                    % (n_panels, 1 if n_panels == 1 else 2)))

        res["written"].append({"path": rel, "label": label,
                               "title": spec["title"],
                               "panels": [pn["file"] for pn in spec["panels"]]})
        if not dry_run:
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "w", encoding="utf-8") as fh:
                fh.write(text)

        if (cfg["label"].lower(), str(n)) not in have_captions:
            new_blocks.append(_image_caption_block(label, dirname, spec))
            res["captions"].append(label)

    if new_blocks and not dry_run:
        path = _captions_path(root)
        prior = ""
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as fh:
                prior = fh.read()
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(prior.rstrip("\n") + "\n\n" + "\n".join(new_blocks))
    return res



# Float folder operations
# ---------------------------------------------------------------------------
# Renumbering is the operation the folder layout exists to make cheap, and it
# is also the one that is easy to get half-right by hand: the folder moves, the
# caption heading keeps the old number, and the two only disagree in the built
# .docx. So it is a command, and it does both halves or neither.

CAPTION_HEADING_EDIT_RE = re.compile(
    "^(##\\s+)(Figure|Table)(\\s+)(S?[0-9]+)(\\s*(?:—|–|-{1,2})\\s*)(\\S+)\\s*$")


def _captions_path(root):
    return os.path.join(root, "plan", "captions.md")


def _read_caption_lines(root):
    path = _captions_path(root)
    if not os.path.isfile(path):
        return []
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read().splitlines()


def float_list(root: str) -> dict:
    res = check(root)
    return {"path": res["path"], "floats": res["floats"],
            "unclaimed_scripts": res["unclaimed_scripts"]}


def float_new(root: str, kind: str, slug: str = "", supplementary: bool = False,
              dry_run: bool = False, art: str = "plotted") -> dict:
    """Add the next float of its kind. Never renumbers anything else.

    `art` is the second axis and it is not the same question as `kind`:
    `kind` is figure-or-table, `art` is plotted-or-drawn. A drawn float is
    marked as one in its own script and told where the drawing happens, so
    that "the user asked for a graphic" survives past the sentence they said
    it in (item 82).
    """
    existing = [f for f in list_float_dirs(root)
                if f["kind"] == kind and f["supplementary"] == supplementary]
    n = max([f["n"] for f in existing] or [0]) + 1
    cfg = FLOAT_KINDS[kind]
    name = float_dir_name(kind, n, supplementary, _slug(slug) if slug else "")
    rel = cfg["dir"] + "/" + name
    target = os.path.join(root, *rel.split("/"))
    created = not os.path.exists(target)
    if created and not dry_run:
        os.makedirs(target, exist_ok=True)
        with open(os.path.join(TEMPLATE_DIR, *cfg["template"].split("/")),
                  "r", encoding="utf-8") as fh:
            body = fh.read()
        if art in ("drawn", "mixed") and kind == "figure":
            body = (DRAWN_BANNER.format(marker=DRAWN_MARKER, n=n)
                    + "\n\n" + body)
        with open(os.path.join(target, cfg["script"]), "w", encoding="utf-8") as fh:
            fh.write(body)
    label = "%s %s%d" % (cfg["label"], "S" if supplementary else "", n)
    out = {"path": os.path.abspath(root), "created": created, "dir": rel,
           "label": label, "script": rel + "/" + cfg["script"], "art": art,
           "caption_block": "## %s — %s" % (label, name), "dry_run": dry_run}
    if art in ("drawn", "mixed") and kind == "figure":
        out["next"] = (
            "this float's art is drawn: run `graphic_figure.py add "
            "<project> --figure %d --panel A` and draw the panel in "
            "PowerPoint. Do not hand-draw it in annotate() calls - that "
            "renders once and is then editable only by somebody who will "
            "edit R." % n)
    return out


def _renumber_plan(floats, kind, supplementary, src, dst):
    """Which folders move where, so a move never lands on an occupied number.

    Moving 3 to 2 shifts 2 up to 3 - the two swap - while moving 5 to 2 walks
    2, 3 and 4 down one. Both are what "put this figure here" means when it is
    said out loud, and neither is what a bare rename does.
    """
    seq = sorted([f for f in floats
                  if f["kind"] == kind and f["supplementary"] == supplementary],
                 key=lambda f: f["n"])
    moving = None
    for f in seq:
        if f["n"] == src:
            moving = f
            break
    if moving is None:
        return []
    rest = [f for f in seq if f["n"] != src]
    at = min(max(dst, 1), len(rest) + 1) - 1
    rest.insert(at, moving)
    return [(f, i + 1) for i, f in enumerate(rest) if f["n"] != i + 1]


def _split_caption_blocks(lines):
    """captions.md as a list of blocks: a heading and everything under it.

    The first block holds whatever precedes the first heading - the scaffolded
    instruction comment lives there - and carries label None so it never moves.
    """
    blocks = [{"lines": [], "label": None, "start": 0, "kind": None,
               "supplementary": False, "n": 0}]
    for i, line in enumerate(lines):
        cm = CAPTION_HEADING_EDIT_RE.match(line)
        if cm:
            num = cm.group(4)
            blocks.append({
                "lines": [line], "start": i,
                "label": cm.group(2) + " " + num,
                "kind": "figure" if cm.group(2) == "Figure" else "table",
                "supplementary": num.startswith("S"),
                "n": int(num.lstrip("S"))})
        else:
            blocks[-1]["lines"].append(line)
    return blocks


def float_renumber(root: str, kind: str, src: int, dst: int,
                   supplementary: bool = False, dry_run: bool = False) -> dict:
    """Move a float to another position: the folders and captions.md together."""
    floats = list_float_dirs(root)
    cfg = FLOAT_KINDS[kind]
    present = [f for f in floats
               if f["kind"] == kind and f["supplementary"] == supplementary
               and f["n"] == src]
    if not present:
        return {"path": os.path.abspath(root), "moves": [], "caption_edits": [],
                "error": "no %s %s%d in %s/" % (
                    cfg["label"], "S" if supplementary else "", src, cfg["dir"])}

    plan = _renumber_plan(floats, kind, supplementary, src, dst)
    moves = []
    for f, n in plan:
        moves.append({
            "from": f["rel"],
            "to": cfg["dir"] + "/" + float_dir_name(kind, n, supplementary, f["slug"]),
            "old_label": f["label"],
            "new_label": "%s %s%d" % (cfg["label"], "S" if supplementary else "", n)})

    if not dry_run and moves:
        # Two passes through a temporary name. Renaming Fig03 to Fig02 while
        # Fig02 still exists either fails or silently merges, depending on the
        # platform - and a silent merge loses a figure.
        base = os.path.join(root, *cfg["dir"].split("/"))
        staged = []
        for m in moves:
            src_p = os.path.join(root, *m["from"].split("/"))
            tmp = os.path.join(base, "__renumber__" + os.path.basename(m["from"]))
            os.rename(src_p, tmp)
            staged.append((tmp, os.path.join(root, *m["to"].split("/"))))
        for tmp, dest in staged:
            os.rename(tmp, dest)

    # captions.md, both halves. Relabelling a heading is not enough: document
    # order in that file IS manuscript order - read_captions() assigns `order`
    # by position and create_floats.R walks it in that order - so a file whose
    # headings read 1, 2, 3 but whose blocks sit in the order 2, 3, 1 builds a
    # co-author document with the figures in the wrong order and every caption
    # numbered correctly. That is the kind of wrong that survives a proofread.
    relabel = {}
    for m in moves:
        relabel[m["old_label"]] = m
    lines = _read_caption_lines(root)
    had_captions = bool(lines)
    blocks = _split_caption_blocks(lines)

    edits = []
    for b in blocks:
        if b["label"] is None:
            continue
        m = relabel.get(b["label"])
        if m is None:
            continue
        # _split_caption_blocks labels a block only when this same pattern
        # matched its first line, so the match is guaranteed here.
        cm = CAPTION_HEADING_EDIT_RE.match(b["lines"][0])
        assert cm is not None
        new_num = m["new_label"].split(" ", 1)[1]
        was = b["lines"][0]
        b["lines"][0] = (cm.group(1) + cm.group(2) + cm.group(3) + new_num
                         + cm.group(5) + os.path.basename(m["to"]))
        b["label"] = m["new_label"]
        b["n"] = int(new_num.lstrip("S"))
        edits.append({"line": b["start"] + 1, "was": was.strip(),
                      "now": b["lines"][0].strip()})

    # Put the blocks of the affected group back in numeric order, into the
    # same positions they already occupied. Only that group moves, so any
    # interleaving with the other kind of float, and anything else in the
    # file, is left exactly where the author put it.
    group = [i for i, b in enumerate(blocks)
             if b["label"] is not None and b["kind"] == kind
             and b["supplementary"] == supplementary]
    reordered = False
    if group:
        want = sorted((blocks[i] for i in group), key=lambda b: b["n"])
        if [b["label"] for b in want] != [blocks[i]["label"] for i in group]:
            reordered = True
            for slot, b in zip(group, want):
                blocks[slot] = b

    if not dry_run and (edits or reordered):
        # Blank lines belong to the block above them, so moving the last block
        # up moves its missing trailing blank with it and the next heading ends
        # up jammed against the body text. Normalise instead of preserving:
        # one blank line after every block but the last.
        out = []
        for j, b in enumerate(blocks):
            body = list(b["lines"])
            while body and not body[-1].strip():
                body.pop()
            if not body and b["label"] is None:
                continue
            out += body
            if j != len(blocks) - 1:
                out.append("")
        with open(_captions_path(root), "w", encoding="utf-8") as fh:
            fh.write("\n".join(out).rstrip("\n") + "\n")

    return {"path": os.path.abspath(root), "moves": moves,
            "caption_edits": edits, "reordered": reordered,
            "dry_run": dry_run, "captions_missing": not had_captions}


FLAT_SCRIPT_RE = re.compile("^(fig|tab)(S?)([0-9]+)[_-]?(.*)$", re.IGNORECASE)


# ---------------------------------------------------------------------------
# float lint - the three traps a static read of a float script can catch
# ---------------------------------------------------------------------------
#
# specs/setup-project-directory.md 5.7.5. Three of the eight traps in 5.7.4
# have right answers and therefore belong in Python; the other five do not, and
# their absence here is a decision rather than an omission:
#
#   trap 1 (figure.R must run last)  enforced in render_all.R
#   trap 3 (height = on >1 row)      a property of a rendered image
#   trap 4 (panel_header/body)       a property of a rendered image
#   trap 5 (R not on PATH)           the shared R-path lookup handles it
#   trap 6 (resolve by stem)         enforced in read_captions.R
#
# IT REPORTS AND NEVER EDITS, and it is NEVER A GATE. Every finding is fixed by
# editing a script the user owns, and a lint that refuses a render teaches
# people to skip the render - the same rule `voice` and `metaprose` follow in
# prose.py.
#
# It deliberately does not parse R semantically, judge a plot, or check that a
# figure shows its claim. The first is a project; the last two have no right
# answer, which is the line this toolkit draws everywhere else.

# A bare ggsave() where save_float() was required (trap 2). Anchored to a call
# so `# ggsave(...)` in a comment and `save_float()`'s own internals do not
# match.
GGSAVE_RE = re.compile(r"(?<![A-Za-z0-9_.])ggsave\s*\(")
SAVE_FLOAT_RE = re.compile(r"(?<![A-Za-z0-9_.])save_float\s*\(")
BUILT_FALSE_RE = re.compile(r"^\s*BUILT\s*<-\s*FALSE\s*$", re.M)

# Column names a script mentions. R has no types to read here, so this is a
# NAME comparison and nothing more - it cannot check meaning and must not
# claim to (trap 8's own caveat). Three spellings cover how the generated
# scripts actually reference a column.
COLUMN_REF_RE = re.compile(
    r"""(?:\.data\[\["([A-Za-z_][A-Za-z_0-9]*)"\]\]"""
    r"""|\$([A-Za-z_][A-Za-z_0-9]*)"""
    r"""|\baes\([^)]*?\b(?:x|y|fill|colour|color|group|shape|size)\s*=\s*"""
    r"""([A-Za-z_][A-Za-z_0-9]*))""")

# Words that look like columns and are not. `aes(x = value)` after a pivot is
# the common one, and flagging it would make the check noise.
NOT_COLUMNS = frozenset({
    "value", "name", "variable", "data", "df", "x", "y", "n", "TRUE", "FALSE",
    "NULL", "NA", "after_stat", "stat", "label", "group", "aes", "vars",
})


def contract_columns(root: str) -> set:
    """Column names `data/data_contract.md` defines.

    Read out of its own tables: the contract is a markdown file with a row per
    column, and the first cell of a row is the name. A project whose contract
    is still the untouched scaffold defines none, and that is reported as
    "unchecked" rather than as every column being undefined.
    """
    text = _read_utf8(os.path.join(root, "data", "data_contract.md"))
    out = set()
    # Only rows of the table whose header opens with `column`. The file also
    # ships a KIND VOCABULARY table - `continuous`, `count`, `proportion` - and
    # reading every first cell in the file harvested those as column names
    # instead. Measured on a fresh scaffold: eight "columns", none of them a
    # column, and every real column then reported as undefined.
    in_columns = False
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            in_columns = False
            continue
        cells = [c.strip().strip("`") for c in line.strip("|").split("|")]
        if not cells:
            continue
        first = cells[0].lower()
        if first in ("column", "name", "field"):
            in_columns = True
            continue
        if set(cells[0]) <= set("-: ") and not cells[0].strip():
            continue
        if not in_columns:
            continue
        if not re.match(r"^[A-Za-z_][A-Za-z_0-9]*$", cells[0]):
            continue
        out.add(cells[0])
    return out


def script_columns(text: str) -> set:
    out = set()
    for m in COLUMN_REF_RE.finditer(text):
        name = m.group(1) or m.group(2) or m.group(3)
        if name and name not in NOT_COLUMNS:
            out.add(name)
    return out


def _caption_claims(root: str) -> dict:
    """label -> the claim sentence, for the floats captions.md describes.

    A written claim is what makes `BUILT <- FALSE` a finding rather than an
    honest statement about a slot nobody has filled in: the pair of facts is
    "somebody wrote what this figure shows" AND "the script still says it does
    not exist".
    """
    out: dict = {}
    label = ""
    in_comment = False
    for raw in _read_caption_lines(root):
        # The scaffolded captions.md carries example headings inside its
        # instruction comment, and those are not floats - the same rule
        # read_captions.R applies, for the same reason.
        if not in_comment and "<!--" in raw:
            in_comment = "-->" not in raw
            continue
        if in_comment:
            in_comment = "-->" not in raw
            continue
        m = CAPTION_HEADING_EDIT_RE.match(raw.rstrip())
        if m:
            label = "%s %s" % (m.group(2), m.group(4).upper())
            out.setdefault(label, "")
            continue
        if not label:
            continue
        body = raw.strip()
        if body.startswith("**") and body.rstrip().endswith("**"):
            out[label] = body.strip("*").strip()
    return {k: v for k, v in out.items() if k}


def _stale_panel_art(fdir: str) -> list[dict]:
    """Panel art whose `.pptx` has changed since it was rendered.

    The staleness signal is a CONTENT HASH and never a modification time,
    because OneDrive rewrites mtimes on sync - a graphic wrongly declared
    current is the whole failure `graphic_figure.py` was written against.
    """
    out = []
    state_path = os.path.join(fdir, ".render_state.json")
    try:
        state = json.loads(_read_utf8(state_path) or "{}")
    except json.JSONDecodeError:
        state = {}
    for name in sorted(os.listdir(fdir)):
        if not name.lower().endswith(".pptx") or name.startswith("~$"):
            continue
        path = os.path.join(fdir, name)
        try:
            with open(path, "rb") as fh:
                digest = hashlib.sha256(fh.read()).hexdigest()
        except OSError:
            continue
        recorded = ((state.get(name) or {}).get("sha256")
                    if isinstance(state.get(name), dict) else state.get(name))
        png = os.path.splitext(name)[0] + ".png"
        rendered = os.path.isfile(os.path.join(fdir, png))
        if not rendered:
            out.append({"pptx": name, "state": "never rendered",
                        "detail": "no %s beside it" % png})
        elif not recorded:
            out.append({"pptx": name, "state": "unknown",
                        "detail": "a .png with no render state is reported "
                                  "stale rather than assumed good"})
        elif recorded != digest:
            out.append({"pptx": name, "state": "stale",
                        "detail": "the .pptx has changed since %s was "
                                  "rendered" % png})
    return out


def _template_text(root: str, kind: str) -> str:
    """The pristine slot script for this float kind, from the project first.

    The project's own `_template/` is read before the toolkit's, because a
    group that has edited its template has changed what pristine MEANS - and
    linting against the toolkit's copy would then report every untouched slot
    in every project as hand-written.
    """
    rel = FLOAT_KINDS.get(kind, {}).get("template", "")
    if not rel:
        return ""
    local = _read_utf8(os.path.join(root, *rel.split("/")))
    if local.strip():
        return local
    return _read_utf8(os.path.join(TEMPLATE_DIR, *rel.split("/")))


def float_lint(root: str, only: str = "") -> dict:
    """Per float: what the script gets wrong, what rendered, what is stale.

    A PRISTINE SLOT IS NOT LINTED, and that is the same rule `idea.py` and
    `graphic_figure.py` already apply for the same reason: compare against the
    template, never guess. The scaffold pre-creates Fig01-Fig04 holding a
    runnable template that references example columns on purpose, so linting
    them reports four identical warnings on a project where nobody has written
    anything - and a scaffold whose first run is full of warnings teaches
    people to ignore warnings, which is expensive later and invisible now.
    """
    defined = contract_columns(root)
    claims = _caption_claims(root)
    res = {"path": os.path.abspath(root),
           "contract_columns": sorted(defined),
           "contract_unchecked": not defined, "floats": [], "notes": []}
    if not defined:
        res["notes"].append(
            "data/data_contract.md defines no columns, so column names are "
            "not checked at all. That is unchecked, not clean.")

    want = (only or "").strip().lower().replace("  ", " ")
    for f in list_float_dirs(root):
        if want and f["label"].lower() != want and f["rel"].lower() != want:
            continue
        fdir = f["path"]
        scripts, findings, rendered, pristine = [], [], [], []
        for name in sorted(os.listdir(fdir)):
            full = os.path.join(fdir, name)
            if name.lower().endswith(RENDER_EXTS) and not name.startswith(
                    ("_", ".")):
                rendered.append(name)
            if not name.endswith(".R") or name.startswith("_"):
                continue
            scripts.append(name)
            text = _read_utf8(full)
            if text.strip() and text.strip() == _template_text(
                    root, f["kind"]).strip():
                pristine.append(name)
                continue

            # trap 2
            if GGSAVE_RE.search(text) and not SAVE_FLOAT_RE.search(text):
                findings.append({
                    "rule": "ggsave_instead_of_save_float",
                    "script": name, "severity": "error",
                    "detail": "calls ggsave() and never save_float(). The "
                              "'.pdf' is then missing, the size is not the "
                              "journal's, no provenance is recorded - and so "
                              "the mock-data watermark never fires."})

            # trap 8, by NAME comparison only
            if defined:
                unknown = sorted(script_columns(text) - defined)
                if unknown:
                    findings.append({
                        "rule": "column_not_in_contract",
                        "script": name, "severity": "warning",
                        "detail": "references %s, which data_contract.md does "
                                  "not define. This is a name comparison and "
                                  "nothing more - a column that exists with a "
                                  "different meaning does not fail here, or "
                                  "anywhere." % ", ".join(unknown)})

            # trap 7
            if BUILT_FALSE_RE.search(text) and claims.get(f["label"]):
                findings.append({
                    "rule": "built_false_with_a_written_claim",
                    "script": name, "severity": "error",
                    "detail": "still sets BUILT <- FALSE, and captions.md "
                              "already carries a claim for %s. The slot then "
                              "renders clean and reports itself unbuilt "
                              "forever, so a finished figure is reported as "
                              "missing by `completeness` and inside the "
                              ".docx." % f["label"]})

        # item 82. The ask is recorded in the script; the art is a .pptx in
        # the folder. A float marked drawn with no source slide is a picture
        # the user cannot change, and it renders perfectly, which is why
        # nothing else catches it.
        marked = any(DRAWN_MARKER in _read_utf8(os.path.join(fdir, nm))
                     for nm in scripts)
        has_art = any(nm.lower().endswith(".pptx")
                      for nm in os.listdir(fdir))
        if marked and not has_art:
            findings.append({
                "rule": "drawn_float_has_no_art",
                "script": scripts[0] if scripts else "-", "severity": "error",
                "detail": "this float is marked as drawn and holds no "
                          "PowerPoint source. Either the art was never "
                          "authored, or it was hand-drawn in R - which "
                          "renders once and is then editable only by "
                          "somebody who will edit R. "
                          "`graphic_figure.py add` writes the slide."})
        if has_art and not marked:
            findings.append({
                "rule": "art_without_the_drawn_marker",
                "script": scripts[0] if scripts else "-",
                "severity": "warning",
                "detail": "this folder holds PowerPoint panel art and no "
                          "script says so. The marker is what lets a later "
                          "round tell a drawn float from a plotted one; "
                          "`graphic_figure.py add` writes it."})

        res["floats"].append({
            "label": f["label"], "dir": f["rel"], "scripts": scripts,
            "art": "drawn" if marked else ("mixed" if has_art else "plotted"),
            "pristine": pristine,
            "rendered": rendered, "claim": claims.get(f["label"], ""),
            "stale_art": _stale_panel_art(fdir),
            "findings": findings})

    if want and not res["floats"]:
        res["notes"].append(
            "no float folder matches %r. `scaffold.py float list` names them."
            % only)
    return res


def print_float_lint(res: dict) -> None:
    print(res["path"])
    for f in res["floats"]:
        print(f"\n  {f['label']}  {f['dir']}")
        if f["claim"]:
            print(f"    claim: {f['claim'][:88]}")
        else:
            print("    claim: none in captions.md - the claim sentence IS the "
                  "specification, and a refinement session without one is "
                  "decorating")
        print(f"    scripts: {', '.join(f['scripts']) or 'none'}"
              + ("   (still the pristine template - not linted)"
                 if f.get("pristine") else ""))
        print(f"    rendered: {', '.join(f['rendered']) or 'nothing yet'}")
        for s in f["stale_art"]:
            print(f"    ART {s['state'].upper()}: {s['pptx']} - {s['detail']}")
        for fi in f["findings"]:
            print(f"    {fi['severity']:8} {fi['script']}: {fi['detail']}")
    for n in res["notes"]:
        print(f"\n  note: {n}")
    total = sum(len(f["findings"]) for f in res["floats"])
    print(f"\n{total} finding(s) across {len(res['floats'])} float(s). "
          f"Nothing here refuses a render:\nevery one is fixed by editing a "
          f"script you own, and a lint that gates\nteaches people to skip the "
          f"render.")


def float_migrate(root: str, dry_run: bool = False) -> dict:
    """Move a flat-layout project's loose scripts into float folders.

    render_all.R now ignores a loose .R rather than running it. Ignoring it
    quietly is how a project that predates the folders renders nothing and
    still reports success, so the runner names those files and this is the
    command it names back.
    """
    moved, unresolved = [], []
    for kind in ("figure", "table"):
        cfg = FLOAT_KINDS[kind]
        base = os.path.join(root, *cfg["dir"].split("/"))
        if not os.path.isdir(base):
            continue
        for nm in sorted(os.listdir(base)):
            path = os.path.join(base, nm)
            if not (os.path.isfile(path) and nm.endswith(".R")):
                continue
            if nm.startswith("_"):
                continue
            stem = os.path.splitext(nm)[0]
            m = FLAT_SCRIPT_RE.match(stem)
            if not m:
                unresolved.append(cfg["dir"] + "/" + nm)
                continue
            supp = m.group(2).upper() == "S"
            n = int(m.group(3))
            slug = _slug(m.group(4)) if m.group(4) else ""
            folder = float_dir_name(kind, n, supp, slug)
            dest = os.path.join(base, folder)
            role = "table" if kind == "table" else "figure"
            # The rendered outputs travel with the script. Leaving figNN.png
            # behind in plan/figures/ leaves a stale image on disk under a
            # name nothing produces any more.
            outputs = []
            for other in sorted(os.listdir(base)):
                if not os.path.isfile(os.path.join(base, other)):
                    continue
                if other != nm and os.path.splitext(other)[0] == stem:
                    outputs.append(cfg["dir"] + "/" + other)
            if not dry_run:
                os.makedirs(dest, exist_ok=True)
                os.replace(path, os.path.join(dest, cfg["script"]))
                for o in outputs:
                    ext = os.path.splitext(o)[1]
                    os.replace(os.path.join(root, *o.split("/")),
                               os.path.join(dest, role + ext))
            moved.append({"script": cfg["dir"] + "/" + nm,
                          "to": cfg["dir"] + "/" + folder + "/" + cfg["script"],
                          "label": "%s %s%d" % (cfg["label"],
                                                "S" if supp else "", n),
                          "outputs": outputs})
    return {"path": os.path.abspath(root), "moved": moved,
            "unresolved": unresolved, "dry_run": dry_run}



def _template_path(name: str, values: dict) -> str:
    if name == "@methods_facts":
        field = values.get("field", "chemistry")
        name = METHODS_TEMPLATES.get(field, METHODS_TEMPLATES["other"])
    if name == "@outline":
        # A review's `##` headings ARE its section list, so its outline
        # template must not seed IMRaD ones: a scaffolded review whose
        # outline said `## Results` would get a results section it never
        # asked for, named by the tool rather than by its author
        # (review-paper 7).
        name = ("plan/outline_review.md"
                if values.get("paper_kind") == "review"
                else "plan/outline.md")
    return os.path.join(TEMPLATE_DIR, name)


def _float_script(root: str, kind: str, n: int, dry_run: bool,
                  supplementary: bool = False) -> tuple[str, bool]:
    """Create one float folder with its script. Returns (relpath, created).

    The script is a copy of the _template folder's, so the copy-me starting
    point and the pre-made slots can never say different things - the same
    reason FILES is an explicit manifest rather than a directory walk.
    """
    cfg = FLOAT_KINDS[kind]
    name = float_dir_name(kind, n, supplementary)
    rel = f"{cfg['dir']}/{name}/{cfg['script']}"
    target = os.path.join(root, *rel.split("/"))
    if os.path.exists(target):
        return rel, False
    if not dry_run:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(os.path.join(TEMPLATE_DIR, *cfg["template"].split("/")),
                  "r", encoding="utf-8") as fh:
            body = fh.read()
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(body)
    return rel, True


def scaffold(root: str, values: dict, dry_run: bool = False,
             only: str | None = None,
             n_figures: int | None = None,
             n_tables: int | None = None,
             rnd: int = 1, paper_kind: str = "research",
             expects_data: str | None = None) -> dict:
    """Create every missing piece. Never touches a file that already exists.

    `only` restricts the run to one top-level subtree of the manifest, so a
    caller that needs just the drafting side can have it without acquiring
    plan/ and data/ as well. `manuscript.py init` is that caller: a
    manuscript-only project - the floats and the analysis managed elsewhere -
    still needs drafts/source_text/, and it must come from THIS manifest.
    A second copy of the drafts layout inside manuscript.py is the
    CAPTION_HEADING_RE problem again, and the copy nobody re-reads is the one
    that drifts.
    """
    review = paper_kind == "review"
    if expects_data is None:
        expects_data = values.get("expects_data", EXPECTS_DATA_DEFAULT)
    expects_data = expects_data_value(expects_data)
    if n_figures is None:
        n_figures = REVIEW_FIGURES if review else DEFAULT_FIGURES
    if n_tables is None:
        n_tables = REVIEW_TABLES if review else DEFAULT_TABLES
    # The two axes compose by union rather than by precedence: a review that
    # expects no data drops what each of them drops, and neither has to know
    # about the other. A meta-analytic review declaring `measurements` keeps
    # its analysis pipeline through the same union, because `measurements`
    # drops nothing.
    data_drops, data_empty_drops = expects_data_drops(expects_data)
    drops = (REVIEW_DROPS if review else frozenset()) | data_drops
    empty_drops = ((REVIEW_EMPTY_DROPS if review else frozenset())
                   | data_empty_drops)
    empty_dirs = list(EMPTY_DIRS) + (REVIEW_EMPTY_ADDS if review else [])

    created: list[str] = []
    skipped: list[str] = []
    collisions: list[dict] = []
    existing_before = os.path.isdir(root) and bool(os.listdir(root))

    def wanted(dest: str) -> bool:
        if dest in drops or dest in empty_drops:
            return False
        if only is None:
            return True
        # Match on the path segment, never a prefix: `only="data"` must not
        # also pull in a future `data_bench/`.
        return dest.split("/", 1)[0] == only

    def ensure_dir(path: str) -> None:
        if not dry_run:
            os.makedirs(path, exist_ok=True)

    ensure_dir(root)

    for dest, template in list(FILES) + (REVIEW_ADDS if review else []):
        if not wanted(dest):
            continue
        dest = source_text_dest(root, dest, rnd)
        target = os.path.join(root, dest)
        twin = _case_twin(root, dest)
        if twin:
            # NOT written and NOT counted as present. Writing it would
            # truncate the author's file on a case-folding filesystem, and
            # counting it present is what let `check` report nothing missing
            # while the template was absent (item 113).
            collisions.append({"manifest": dest, "on_disk": twin})
            continue
        if _exists_exact(root, dest):
            skipped.append(dest)
            continue
        created.append(dest)
        if dry_run:
            continue
        ensure_dir(os.path.dirname(target) or root)
        if template is None:
            open(target, "w", encoding="utf-8").close()
            continue
        src = _template_path(template, values)
        with open(src, "r", encoding="utf-8") as fh:
            body = fh.read()
        # Only text templates carry placeholders; R sources read project.yml at
        # run time instead, so they stay valid R and can be linted in place.
        if dest.endswith((".md", ".yml", ".bib")):
            body = _render(body, values)
        # A shell script keeps LF on Windows too: Git Bash reads a CRLF
        # script as commands ending in a stray carriage return and fails.
        with open(target, "w", encoding="utf-8",
                  newline="\n" if dest.endswith(".sh") else None) as fh:
            fh.write(body)

    for d in empty_dirs:
        if not wanted(d):
            continue
        keep = os.path.join(root, d, ".gitkeep")
        if os.path.isdir(os.path.join(root, d)) and os.path.exists(keep):
            skipped.append(d + "/")
            continue
        created.append(d + "/")
        if not dry_run:
            ensure_dir(os.path.join(root, d))
            open(keep, "w", encoding="utf-8").close()

    # The float slots. Created after the manifest so the _template folders
    # they are copied from already exist, and skipped entirely under --only
    # unless the plan/ subtree is what was asked for.
    floats: list[str] = []
    if only in (None, "plan"):
        for kind, count in (("figure", n_figures), ("table", n_tables)):
            for i in range(1, max(0, count) + 1):
                rel, made = _float_script(root, kind, i, dry_run)
                (created if made else skipped).append(rel)
                if made:
                    floats.append(os.path.dirname(rel))

    return {
        "path": os.path.abspath(root),
        "created": created,
        "skipped": skipped,
        # Neither created nor skipped: a manifest entry whose name is taken
        # on disk by a file that differs only in case (item 113).
        "collisions": collisions,
        "float_folders": floats,
        "already_set_up": not created,
        "was_populated": existing_before,
        "dry_run": dry_run,
        "only": only,
        "field": values.get("field"),
        "paper_kind": paper_kind,
        "expects_data": expects_data,
        "offers": offers_for(expects_data, paper_kind),
        "target_journal": values.get("target_journal"),
    }


# --- CASE COLLISIONS (item 113) --------------------------------------------
#
# `os.path.exists` answers the FILESYSTEM's question, and on Windows and macOS
# that question folds case. So an author's own `readme.md` made the scaffold
# report its `README.md` "already present", which is correct behavior for the
# never-overwrite rule and the wrong answer here: the template was never
# written, `check` reported `missing: []`, and the same file came back as an
# unfiled stray - one entry that was simultaneously the scaffold's own and
# something to move. Measured 2026-09-20; invisible on Linux, where the folder
# simply gets both files.
#
# These compare EXACTLY, on every platform, by reading the directory rather
# than asking whether a path exists. On a case-sensitive filesystem that is
# the same answer `os.path.exists` gives, so there is no platform probe here
# and nothing to get wrong on one of them.


def _exists_exact(root: str, rel: str) -> bool:
    """Does `rel` exist under `root` with exactly this spelling."""
    here = root
    for part in rel.replace("\\", "/").split("/"):
        if not part:
            continue
        try:
            names = os.listdir(here)
        except OSError:
            return False
        if part not in names:
            return False
        here = os.path.join(here, part)
    return True


def _case_twin(root: str, rel: str) -> str:
    """The on-disk name that differs from `rel`'s last part only in case.

    Empty when there is none - including when the exact name is there, which
    is the ordinary case and not a collision.
    """
    rel = rel.replace("\\", "/").rstrip("/")
    parent, _, leaf = rel.rpartition("/")
    here = os.path.join(root, *parent.split("/")) if parent else root
    try:
        names = os.listdir(here)
    except OSError:
        return ""
    if leaf in names:
        return ""
    for name in names:
        if name.lower() == leaf.lower():
            return (parent + "/" + name) if parent else name
    return ""


def check(root: str) -> dict:
    """What is present, what is missing, and whether anything has been rendered.

    What counts as MISSING depends on what the project said it is. A review
    has no analysis pipeline and a project that declared `expects_data: none`
    has no data/ at all; reporting either as a gap on every run is how a
    scaffold report gets ignored, and an ignored report is worse than no
    report. Both are read from project.yml rather than guessed, so a folder
    that is absent because nobody has run the scaffold yet still reports as
    missing - which is the case the report exists for.
    """
    project = read_project_yml(root)
    review = (project.get("paper_kind") or "research").strip() == "review"
    expects = expects_data_value(project.get("expects_data"))
    data_drops, data_empty_drops = expects_data_drops(expects)
    drops = (REVIEW_DROPS if review else frozenset()) | data_drops
    empty_drops = ((REVIEW_EMPTY_DROPS if review else frozenset())
                   | data_empty_drops)
    empty_dirs = list(EMPTY_DIRS) + (REVIEW_EMPTY_ADDS if review else [])
    manifest = list(FILES) + (REVIEW_ADDS if review else [])

    present, missing, out_of_scope = [], [], []
    collisions: list[dict] = []
    for dest, _ in manifest:
        dest = source_text_dest(root, dest)
        if dest in drops:
            out_of_scope.append(dest)
            continue
        # EXACT, not `os.path.exists` (item 113). A `readme.md` the author
        # wrote is not this manifest's `README.md`, and reporting it present
        # is how the one command whose job is saying what is missing said
        # nothing was.
        if _exists_exact(root, dest):
            present.append(dest)
            continue
        twin = _case_twin(root, dest)
        if twin:
            collisions.append({"manifest": dest, "on_disk": twin})
        missing.append(dest)
    for d in empty_dirs:
        if d in empty_drops:
            out_of_scope.append(d + "/")
            continue
        p = os.path.join(root, d)
        (present if os.path.isdir(p) else missing).append(d + "/")
    rendered = [g for g in GENERATED if os.path.exists(os.path.join(root, g))]

    # Float folders are reported, never required. How many floats a paper has
    # is the paper's business, so a deleted Fig03 is not a defect - but a
    # folder holding no script, or a loose .R left behind by the flat layout,
    # is worth naming because both render nothing and look fine.
    floats = list_float_dirs(root)
    float_report = []
    for f in floats:
        scripts = sorted(n for n in os.listdir(f["path"])
                         if n.endswith(".R") and not n.startswith("_"))
        renders = sorted(n for n in os.listdir(f["path"])
                         if n.lower().endswith(RENDER_EXTS)
                         and not n.startswith(("_", ".")))
        float_report.append({"label": f["label"], "dir": f["rel"],
                             "kind": f["kind"], "number": f["number"],
                             "supplementary": f["supplementary"],
                             "scripts": scripts, "renders": renders,
                             "empty": not scripts})
    loose = []
    for cfg in FLOAT_KINDS.values():
        base = os.path.join(root, *cfg["dir"].split("/"))
        if not os.path.isdir(base):
            continue
        loose += [f"{cfg['dir']}/{n}" for n in sorted(os.listdir(base))
                  if n.endswith(".R") and not n.startswith("_")
                  and os.path.isfile(os.path.join(base, n))]

    return {
        "path": os.path.abspath(root),
        "exists": os.path.isdir(root),
        "scaffolded": not missing,
        "present": present,
        "missing": missing,
        # A manifest entry whose name is taken on disk by a file differing
        # only in case. It is MISSING, and this says why (item 113).
        "collisions": collisions,
        "rendered": rendered,
        "out_of_scope": out_of_scope,
        "paper_kind": "review" if review else "research",
        "expects_data": expects,
        "floats": float_report,
        "unclaimed_scripts": loose,
        "proposed_methods": proposed_methods_report(root),
        "project": read_project_yml(root),
    }


# specs/idea-generation.md 11.4, items 2 and 3. `data/methods_proposed.yml` is
# written by `idea.py`, is not in the manifest, and is read by nothing - so
# without this it is a file in `data/` that nobody is reminded exists.
PROPOSED_ENTRY_RE = re.compile(r"^[ \t]{2}([a-z][A-Za-z_0-9]*):[ \t]*$", re.M)


def proposed_methods_report(root: str) -> dict:
    """What `data/methods_proposed.yml` holds, and what has been superseded.

    Two facts, and the second is the one worth having: a key that is now
    filled in `methods_facts.yml` and still sitting in `methods_proposed.yml`
    is a probable un-deleted block. Not an error - the author may be comparing
    the two - but worth naming, because a stale proposal next to a real value
    is how the wrong one gets copied later.
    """
    path = os.path.join(root, "data", "methods_proposed.yml")
    out = {"present": os.path.isfile(path), "entries": 0, "superseded": []}
    if not out["present"]:
        return out
    text = _read_utf8(path)
    entries = PROPOSED_ENTRY_RE.findall(text)
    out["entries"] = len(entries)
    have = confirmed_keys(_read_utf8(os.path.join(root, "data",
                                                  "methods_facts.yml")))
    out["superseded"] = sorted(set(entries) & have)
    return out



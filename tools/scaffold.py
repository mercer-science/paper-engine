_PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")


def _render(text: str, values: dict) -> str:
    """Substitute {{key}} placeholders. An unknown key is left alone rather than
    blanked - a stray brace in a template should be visible, not silently eaten."""
    return _PLACEHOLDER.sub(lambda m: str(values.get(m.group(1), m.group(0))), text)


def _slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return s or "project"


def build_values(project_name: str, title: str = "", short_name: str = "",
                 field: str = "chemistry", journal: str = "", pi: str = "",
                 one_liner: str = "", paper_kind: str = "research",
                 expects_data: str = EXPECTS_DATA_DEFAULT) -> dict:
    title = title.strip()
    short_name = short_name.strip() or _slug(project_name)
    return {
        "project_name": project_name,
        "title": title,
        "short_name": short_name,
        "field": field,
        "paper_kind": paper_kind,
        "expects_data": expects_data_value(expects_data),
        "target_journal": journal.strip(),
        "pi": pi.strip(),
        "created": datetime.date.today().isoformat(),
        "title_or_name": title or project_name,
        "one_liner": one_liner.strip() or
                     "<!-- One line: what this paper will show. -->",
    }


def read_project_yml(root: str) -> dict:
    """Existing project.yml values, so a re-run does not contradict them.

    Deliberately a small hand parser rather than a PyYAML dependency: this reads
    flat `key: value` pairs and nothing else, which is all project.yml has at
    the top level, and the engine stays runnable with a bare Python.
    """
    path = os.path.join(root, "project.yml")
    out: dict = {}
    if not os.path.isfile(path):
        return out
    try:
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.split("#", 1)[0].rstrip()
                m = re.match(r"^([a-z_]+):\s*(.*)$", line)
                if m:
                    out[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    except OSError:
        return {}
    return out



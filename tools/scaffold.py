# The folder-name grammar, and a contract with plan/theme/read_captions.R's
# FLOAT_DIR_RE. Change one, change both, and re-run tests/scaffold.py - it
# reads the regex out of the .R file and asserts the two agree.
#
# Tolerant on purpose. Fig01, Fig1, Fig 1, Fig_1, Figure01 and
# Fig01_yield_by_catalyst are all Figure 1: the trailing slug is for whoever is
# reading the file tree, and the number is the identity. That is what lets a
# slug be added or changed without an edit anywhere else.
FLOAT_DIR_RE = re.compile(
    r"^(Fig|Figure|Tab|Table)[ _-]?(S?)([0-9]+)([ _-].*)?$", re.IGNORECASE)


def parse_float_dir(name: str) -> dict | None:
    """A float folder name -> its canonical identity, or None if it is not one."""
    m = FLOAT_DIR_RE.match(name)
    if not m:
        return None
    kind = "figure" if m.group(1).lower().startswith("fig") else "table"
    supp = m.group(2).upper() == "S"
    n = int(m.group(3))
    num = ("S" if supp else "") + str(n)
    return {"kind": kind, "type": FLOAT_KINDS[kind]["label"], "n": n,
            "number": num, "supplementary": supp,
            "label": f"{FLOAT_KINDS[kind]['label']} {num}",
            "dir": name, "slug": (m.group(4) or "").lstrip(" _-")}


def float_dir_name(kind: str, n: int, supplementary: bool = False,
                   slug: str = "") -> str:
    """The canonical folder name: Fig01, FigS01, Table01, Fig01_yield."""
    base = f"{FLOAT_KINDS[kind]['prefix']}{'S' if supplementary else ''}{n:02d}"
    return f"{base}_{slug}" if slug else base


def list_float_dirs(root: str) -> list[dict]:
    """Every float folder in the project, in manuscript order.

    Supplementary floats follow the main sequence, each in numeric order -
    the same ordering list_float_dirs() uses in R, because the preview, the
    Word floats and this engine must agree on what "the float set" is.
    """
    out: list[dict] = []
    for cfg in FLOAT_KINDS.values():
        base = os.path.join(root, *cfg["dir"].split("/"))
        if not os.path.isdir(base):
            continue
        for nm in sorted(os.listdir(base)):
            if nm.startswith(("_", ".")):
                continue
            if not os.path.isdir(os.path.join(base, nm)):
                continue
            if ONEDRIVE_CONFLICT_RE.search(nm):
                continue
            f = parse_float_dir(nm)
            if f is None:
                continue
            f["path"] = os.path.join(base, nm)
            f["rel"] = cfg["dir"] + "/" + nm
            out.append(f)
    out.sort(key=lambda f: (f["kind"] != "figure", f["supplementary"], f["n"]))
    return out



def _journals_of(root: str) -> list[str]:
    """Journal folders under the drafting directory, by name."""
    drafts = os.path.join(root, "drafts")
    if not os.path.isdir(drafts):
        drafts = root
    out = []
    for name in sorted(os.listdir(drafts)) if os.path.isdir(drafts) else []:
        d = os.path.join(drafts, name)
        if os.path.isdir(d) and os.path.isdir(
                os.path.join(d, "journal_requirements")):
            out.append(name)
    return out



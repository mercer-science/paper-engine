# ---------------------------------------------------------------------------
# Adopting a folder that already exists, and surveying what it holds
# ---------------------------------------------------------------------------
# A project that started as a folder full of work is the common case, not the
# exception: somebody has been collecting data for four months and now wants
# the pipeline around it. `scaffold` already handles half of that - it adds
# what is missing and never touches what is there - and the half it does not
# handle is the reason the folder looked like a mess in the first place. Forty
# files sitting at the root are not wrong, they are unfiled.
#
# So: `adopt` = `scaffold` + a proposal for everything the scaffold does not
# recognise. The proposal is the product. Moving files is the part that is
# opt-in, and only ever for the entries the rules are certain about.
#
# THREE RULES THIS OBEYS, AND THEY ARE NOT NEGOTIABLE:
#
#   1. It never deletes. Not a file, not a folder, not an empty one left
#      behind by a move.
#   2. It never overwrites. A move whose destination exists is downgraded to
#      a conflict and reported; it is not resolved by renaming, because the
#      two files might be the same file and only the user knows.
#   3. It moves nothing without `--apply`, and even then only entries whose
#      confidence is `clear`. Everything else comes back as a question for
#      the skill to ask a human.

# Noise. Never classified, never moved, never reported as useful - listing
# Thumbs.db as an unexplained directory entry is how a report gets skimmed.
ADOPT_IGNORE_NAMES = {".ds_store", "thumbs.db", "desktop.ini", ".gitkeep",
                      ".here", ".rhistory", ".rdata", ".gitattributes"}
ADOPT_IGNORE_PREFIXES = ("~$", ".~lock.")
ADOPT_IGNORE_DIRS = {".git", ".svn", "__pycache__", ".rproj.user", ".vscode",
                     ".claude", ".ipynb_checkpoints", "node_modules",
                     ".pytest_cache", ".venv", "venv", "renv"}

# What a file is FOR, from its extension. `useful_for` is the half the writing
# engine reads: it is not "where does this go", it is "could this feed a
# sentence, a citation, a number or a panel".
ROLE_BY_EXT = {
    "drafting":  {".md", ".txt", ".docx", ".doc", ".odt", ".rtf", ".tex"},
    "citations": {".pdf", ".bib", ".ris", ".nbib", ".enw", ".xml"},
    "data":      {".csv", ".tsv", ".dat", ".xlsx", ".xls", ".parquet",
                  ".sav", ".dta"},
    "floats":    {".png", ".jpg", ".jpeg", ".tif", ".tiff", ".svg", ".eps",
                  ".pptx", ".ppt", ".ai", ".psd", ".gif", ".bmp",
                  ".dm3", ".dm4", ".mrc", ".mrcs", ".emd", ".ser", ".nd2",
                  ".czi", ".lif", ".spe"},
    "analysis":  {".r", ".rmd", ".qmd", ".py", ".ipynb", ".m", ".jl", ".do"},
}

EXTRA_SOURCE_ROLES = ("drafting", "citations", "data", "floats", "analysis",
                      "methods", "ignore")


def role_of_ext(ext: str) -> str:
    ext = ext.lower()
    for role, exts in ROLE_BY_EXT.items():
        if ext in exts:
            return role
    return ""



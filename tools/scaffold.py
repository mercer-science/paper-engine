def _norm_name(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", name.lower())


def _name_keys(name: str) -> list:
    """The whole name first, then its words.

    `Raw Data` has to match `rawdata`, and `seminar slides` has to match
    `slides` - so both the collapsed name and each separated word are tried,
    whole name first. Word matching is what makes the table survive real
    folder names, which are almost never one word.
    """
    keys = [_norm_name(name)]
    keys += [w for w in re.split(r"[^a-z0-9]+", name.lower()) if w]
    seen, out = set(), []
    for k in keys:
        if k and k not in seen:
            seen.add(k)
            out.append(k)
    return out


def _manifest_paths(root: str) -> set:
    """Every top-level name the tree itself owns."""
    out = {".here", ".git", ".gitignore", ".claude", ".vscode"}
    for dest, _ in FILES + REVIEW_ADDS:
        out.add(source_text_dest(root, dest).split("/", 1)[0])
    for d in EMPTY_DIRS + REVIEW_EMPTY_ADDS:
        out.add(d.split("/", 1)[0])
    # Every source_text_rN the project actually has, not only the current one.
    if source_text_folders(os.path.join(root, "drafts")):
        out.add("drafts")
    return out


def _is_noise(name: str, is_dir: bool) -> bool:
    low = name.lower()
    if low in ADOPT_IGNORE_NAMES:
        return True
    if any(low.startswith(pre) for pre in ADOPT_IGNORE_PREFIXES):
        return True
    if is_dir and low in ADOPT_IGNORE_DIRS:
        return True
    return ONEDRIVE_CONFLICT_RE.search(name) is not None


def _walk_summary(path: str, cap: int = 4000) -> dict:
    """Extension histogram and role histogram for one directory, recursively.

    Capped rather than unbounded: a folder of 200,000 frames is a real thing
    in an imaging project, and the answer to "what is in here" does not get
    better after the first few thousand.
    """
    exts: dict = {}
    roles: dict = {}
    n = 0
    truncated = False
    for _dirpath, dirnames, filenames in os.walk(path):
        dirnames[:] = [d for d in dirnames
                       if d.lower() not in ADOPT_IGNORE_DIRS]
        for fn in filenames:
            if _is_noise(fn, False):
                continue
            n += 1
            if n > cap:
                truncated = True
                break
            ext = os.path.splitext(fn)[1].lower()
            exts[ext] = exts.get(ext, 0) + 1
            role = role_of_ext(ext)
            if role:
                roles[role] = roles.get(role, 0) + 1
        if truncated:
            break
    return {"files": n, "extensions": exts, "roles": roles,
            "truncated": truncated}


def _classify_dir(name: str, summary: dict) -> dict:
    """A top-level directory -> where it might go and what it might be for.

    Name first, contents second. A folder called `old/` full of CSVs is
    retired work, not raw data, and the name is the only place that fact is
    written down.
    """
    keys = _name_keys(name)
    for i, key in enumerate(keys):
        for names, dest, conf, why in DIR_RULES:
            if key not in names:
                continue
            # A match on ONE WORD of a longer name is a weaker claim than a
            # match on the whole name, so it never reaches `clear` and
            # therefore never reaches `--apply`. `images/` is the images; a
            # folder called `notes on images` is not, and the only cheap way
            # to keep those apart is to stop trusting the partial match with
            # a file move.
            if i > 0 and conf == "clear":
                conf = "likely"
                why = "%s - matched on the word %r, not the whole name" % (
                    why, key)
            return {"proposal": dest, "confidence": conf, "why": why}
    # No name match: let the contents speak, but never confidently. A folder
    # somebody named themselves has a meaning this table does not know.
    roles = summary.get("roles") or {}
    if roles:
        top = max(roles, key=lambda r: roles[r])
        dest = {"data": "data/raw", "floats": "data/raw_images",
                "citations": "plan/relevant_literature",
                "analysis": "data/analysis"}.get(top, "")
        n = summary.get("files") or 0
        return {"proposal": dest, "confidence": "unknown",
                "why": "not a name this engine knows; %d of its %d file%s "
                       "look%s like %s"
                       % (roles[top], n, "" if n == 1 else "s",
                          "s" if roles[top] == 1 else "", top)}
    return {"proposal": "", "confidence": "unknown",
            "why": "not a name this engine knows, and nothing inside it "
                   "says what it is"}


def _classify_file(name: str) -> dict:
    ext = os.path.splitext(name)[1].lower()
    for exts, dest, conf, why in FILE_RULES:
        if ext in exts:
            return {"proposal": dest, "confidence": conf, "why": why}
    return {"proposal": "", "confidence": "unknown",
            "why": "no rule for %s" % (ext or "a file with no extension")}


def _useful_for(summary: dict) -> list:
    """The roles a thing could serve, commonest first."""
    roles = summary.get("roles") or {}
    return sorted(roles, key=lambda r: (-roles[r], r))


# How many entries a depth walk may classify before it stops and says so.
# `_walk_summary` already caps at 4000 with the reasoning written in - a
# folder of 200,000 frames is a real thing in an imaging project - and a
# classify-every-entry walk needs the same cap. A reorganize report that
# silently covered the first 4000 of 60,000 files is a report that says the
# folder is tidier than it is (reorganize-directory 4.3).
DEPTH_WALK_CAP = 4000


def survey(root: str, include_recorded: bool = False,
           depth: int = 1) -> dict:
    """Every top-level entry the tree does not explain, and what it might be for.

    This is the read half of `adopt`, and it is what `writing-engine` calls:
    it proposes nothing about moving anything, it only answers "there is a
    folder here that is not part of the structure - could it feed the paper?"
    A `survey` that reported every stray file as a problem would be a survey
    nobody runs twice, so noise is dropped and anything already answered for
    in project.yml comes back under `recorded` rather than as a new question.
    """
    res = {"path": os.path.abspath(root), "exists": os.path.isdir(root),
           "unexpected": [], "recorded": [], "ignored": [], "collisions": [],
           "depth": max(1, int(depth or 1)), "truncated": False}
    if not res["exists"]:
        return res

    known = _manifest_paths(root)
    answered = {e["path"]: e for e in read_extra_sources(root)}
    res["recorded"] = list(answered.values())

    folded = {k.lower(): k for k in known}
    # --- the walk (reorganize-directory 4) --------------------------------
    #
    # `--depth 1` is what this command always did and is still the default:
    # "my folder has folders in it" and "reorganise the inside of my
    # folders" are different requests and only the user knows which one they
    # are making. `setup-project-directory.md` 13.3's "top level only" is
    # not thrown away here - the fence MOVED. Four rules hold at any depth,
    # and each is a refusal:
    #
    #   1. never descend into a directory the tree owns - plan/, data/,
    #      drafts/, obsolete/, sandbox/ are the structure's business;
    #   2. never descend into a directory whose own NAME matched a rule. A
    #      folder that has a meaning moves whole; taking it apart on a rules
    #      table is exactly what 13.3 refused;
    #   3. descend only into `unknown`-tier directories - the ones where
    #      "there is a misc/ with four months of everything in it" lives,
    #      and the only place depth buys anything;
    #   4. a deep entry may never be `clear`, so `--apply` cannot reach it.
    queue: list[tuple[str, int]] = [("", 1)]
    seen_count = 0
    max_depth = res["depth"]
    while queue:
        rel_parent, level = queue.pop(0)
        here = os.path.join(root, *rel_parent.split("/")) if rel_parent else root
        try:
            names = sorted(os.listdir(here))
        except OSError:
            continue
        for name in names:
            rel = (rel_parent + "/" + name) if rel_parent else name
            full = os.path.join(here, name)
            is_dir = os.path.isdir(full)
            if level == 1:
                if name in known:
                    continue
                if name.lower() in folded:
                    # A case twin of a name the tree owns. It is reported as
                    # a COLLISION and never as a stray: one entry that is
                    # both the scaffold's own and something to move is how a
                    # file ends up being moved out from under a template
                    # (item 113).
                    res["collisions"].append({"manifest": folded[name.lower()],
                                              "on_disk": name})
                    continue
            if _is_noise(name, is_dir):
                res["ignored"].append(rel + ("/" if is_dir else ""))
                continue
            if seen_count >= DEPTH_WALK_CAP:
                res["truncated"] = True
                queue = []
                break
            seen_count += 1
            if is_dir:
                summary = _walk_summary(full)
                cls = _classify_dir(name, summary)
            else:
                ext = os.path.splitext(name)[1].lower()
                role = role_of_ext(ext)
                summary = {"files": 1, "extensions": {ext: 1},
                           "roles": {role: 1} if role else {},
                           "truncated": False}
                cls = _classify_file(name)
            confidence = cls["confidence"]
            why = cls["why"]
            if level > 1 and confidence == "clear":
                # Rule 4. The proposal is still the product and it is still
                # a human who says yes.
                confidence = "likely"
                why = ("%s - and it was found %d level%s down, so it is a "
                       "proposal rather than a certainty: `--apply` moves "
                       "top-level entries only"
                       % (why, level - 1, "" if level == 2 else "s"))
            entry = {"path": rel, "kind": "dir" if is_dir else "file",
                     "depth": level,
                     "files": summary["files"],
                     "extensions": summary["extensions"],
                     "truncated": summary["truncated"],
                     "useful_for": _useful_for(summary),
                     "proposal": cls["proposal"], "confidence": confidence,
                     "why": why}
            descend = (is_dir and level < max_depth
                       and cls["confidence"] == "unknown"   # rule 3 and 2
                       and rel not in known)                # rule 1
            if descend:
                queue.append((rel, level + 1))
            if rel in answered and not include_recorded:
                continue
            entry["answered_as"] = (answered.get(rel) or {}).get("use", "")
            res["unexpected"].append(entry)

    # An entry recorded in project.yml whose folder has since been deleted or
    # renamed is worth saying out loud: the answer is now pointing at nothing,
    # and a writing round that tries to read it would be reading a gap.
    for rec in res["recorded"]:
        rec["exists"] = os.path.exists(os.path.join(root, rec["path"]))
    return res


def print_survey(res: dict) -> None:
    if not res["exists"]:
        print("No such directory: %s" % res["path"])
        return
    if not res["unexpected"] and not res["recorded"]:
        print("Nothing outside the structure. %s" % res["path"])
        _print_collisions(res)
        return
    _print_collisions(res)
    for e in res["unexpected"]:
        mark = "/" if e["kind"] == "dir" else ""
        use = ", ".join(e["useful_for"]) or "nothing this engine reads"
        print("  %-28s %4d file(s)   could feed: %s"
              % (e["path"] + mark, e["files"], use))
        print("      %s" % e["why"])
        if e["proposal"]:
            print("      proposal: %s   (%s)" % (e["proposal"],
                                                 e["confidence"]))
    for r in res["recorded"]:
        gone = "" if r.get("exists", True) else "   MISSING - it is gone now"
        print("  recorded  %-26s use: %s%s" % (r["path"], r["use"], gone))
    if res["ignored"]:
        print("  ignored: %s" % ", ".join(res["ignored"]))


# --- the answers, recorded in project.yml -----------------------------------
# One block, indented, so read_project_yml()'s flat `key: value` parser walks
# straight past it and every existing reader of project.yml is unaffected.
# It lives in project.yml rather than in a journal's writing_config.yml
# because the answer is a fact about the PROJECT: a folder of lab notes is
# just as readable when the paper moves to its second journal.

EXTRA_SOURCES_KEY = "extra_sources:"
_EXTRA_ITEM_RE = re.compile(r"^\s+-\s+path:\s*(.+?)\s*$")
_EXTRA_FIELD_RE = re.compile(r"^\s+([a-z_]+):\s*(.*?)\s*$")


def _extra_sources_span(lines: list[str]) -> tuple[int, int] | None:
    """(start, end) of the extra_sources block, end exclusive."""
    for i, line in enumerate(lines):
        if line.split("#", 1)[0].rstrip() == EXTRA_SOURCES_KEY or \
                line.startswith(EXTRA_SOURCES_KEY):
            j = i + 1
            while j < len(lines) and (not lines[j].strip()
                                      or lines[j][:1] in (" ", "\t")):
                j += 1
            return i, j
    return None


def read_extra_sources(root: str) -> list:
    """What this project has already decided about folders outside the tree."""
    path = os.path.join(root, "project.yml")
    if not os.path.isfile(path):
        return []
    try:
        lines = _read_utf8(path).splitlines()
    except OSError:
        return []
    span = _extra_sources_span(lines)
    if span is None:
        return []
    out: list = []
    for line in lines[span[0] + 1:span[1]]:
        bare = line.split("#", 1)[0] if line.lstrip().startswith("#") else line
        if not bare.strip():
            continue
        m = _EXTRA_ITEM_RE.match(bare)
        if m:
            out.append({"path": _unquote_scalar(m.group(1)), "use": "",
                        "note": ""})
            continue
        m = _EXTRA_FIELD_RE.match(bare)
        if m and out and m.group(1) in ("use", "note"):
            out[-1][m.group(1)] = _unquote_scalar(m.group(2))
    return [e for e in out if e["path"]]


def _unquote_scalar(v: str) -> str:
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


EXTRA_SOURCES_HEADER = """extra_sources:                   \
# folders outside the standard tree, and what
                                 # writing-engine may do with each. Written by
                                 # `scaffold.py survey --use/--ignore`, and
                                 # hand-editable. `use:` is one of drafting |
                                 # citations | data | floats | analysis |
                                 # methods | ignore. An entry here is ASKED
                                 # ABOUT ONCE and never again."""


def record_extra_source(root: str, path: str, use: str, note: str = "",
                        dry_run: bool = False) -> dict:
    """Write one answer into project.yml's extra_sources block.

    Replaces an existing answer for the same folder rather than appending a
    second one: re-answering is a normal thing to do, and two entries for one
    folder is a file that contradicts itself.
    """
    res = {"path": path, "use": use, "note": note, "action": "", "errors": []}
    if use not in EXTRA_SOURCE_ROLES:
        res["errors"].append("use must be one of: %s"
                             % ", ".join(EXTRA_SOURCE_ROLES))
        return res
    target = os.path.join(root, "project.yml")
    if not os.path.isfile(target):
        res["errors"].append("no project.yml at %s - scaffold it first"
                             % os.path.abspath(root))
        return res
    entries = read_extra_sources(root)
    res["action"] = "update" if any(e["path"] == path for e in entries) \
        else "add"
    entries = [e for e in entries if e["path"] != path]
    entries.append({"path": path, "use": use, "note": note})
    entries.sort(key=lambda e: e["path"])

    body = [EXTRA_SOURCES_HEADER]
    for e in entries:
        body.append("  - path: %s" % e["path"])
        body.append("    use: %s" % e["use"])
        if e["note"]:
            body.append("    note: %s" % e["note"].replace("\n", " "))
    block = "\n".join(body)

    text = _read_utf8(target)
    lines = text.splitlines()
    span = _extra_sources_span(lines)
    if span is None:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        new = "\n".join(lines[:span[0]] + block.splitlines()
                        + lines[span[1]:]) + "\n"
    res["entries"] = entries
    if not dry_run:
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(new)
    return res


# A project.yml written before a key existed does not have that key, and a
# project adopted from a folder of work is exactly the project whose
# project.yml is old. So: an ABSENT key may be filled in, once, from the flag
# that supplied it.
#
# This is not a hole in "project.yml is never overwritten". Nothing recorded
# is changed and nothing is removed - a key that is already there always
# wins, and the disagreement is still reported through `ignored_flags`. What
# is added is a fact the user just stated out loud, into the only file that
# would otherwise forget it by the next command.
PROJECT_KEY_ORDER = ["title", "short_name", "field", "paper_kind",
                     "expects_data", "target_journal"]

PROJECT_KEY_COMMENTS = {
    "paper_kind": "# research | review. Absent reads as research",
    "expects_data": "# measurements | images | none",
    "field": "# chemistry | biochemistry | other",
    "github": "# declined: GitHub is not offered again",
}


def record_project_key(root: str, key: str, value: str,
                       dry_run: bool = False) -> dict:
    """Fill in one ABSENT flat key in project.yml. Never changes one that is
    already recorded, and never touches a file that does not exist."""
    res = {"key": key, "value": value, "action": "skip", "errors": []}
    path = os.path.join(root, "project.yml")
    if not os.path.isfile(path):
        res["errors"].append("no project.yml at %s" % os.path.abspath(root))
        return res
    if (read_project_yml(root).get(key) or "").strip():
        res["action"] = "already recorded"
        return res
    text = _read_utf8(path)
    lines = text.splitlines()
    comment = PROJECT_KEY_COMMENTS.get(key, "")
    entry = "%s: %s" % (key, value)
    if comment:
        entry = "%-32s%s" % (entry, comment)

    # Place it next to the keys it belongs with, so the file stays readable.
    # Falls back to the end, which is always correct and only ever ugly.
    want = PROJECT_KEY_ORDER.index(key) if key in PROJECT_KEY_ORDER else -1
    at = None
    if want >= 0:
        for i, line in enumerate(lines):
            m = re.match(r"^([a-z_]+):", line)
            if not m or m.group(1) not in PROJECT_KEY_ORDER:
                continue
            if PROJECT_KEY_ORDER.index(m.group(1)) < want:
                at = i + 1
    if at is None:
        at = len(lines)
        for i, line in enumerate(lines):
            if line.startswith(EXTRA_SOURCES_KEY):
                at = i
                break
    lines.insert(at, entry)
    res["action"] = "added"
    if not dry_run:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines).rstrip("\n") + "\n")
    return res



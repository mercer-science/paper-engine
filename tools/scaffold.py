    coll = chk.get("collisions") or []
    row("Structure",
        "%d present, %d missing, nothing overwritten%s"
        % (len(chk["present"]), len(chk["missing"]),
           "" if not coll else
           "; %d name collision(s): %s" % (
               len(coll), ", ".join("%s vs %s" % (c["manifest"], c["on_disk"])
                                    for c in coll))),
        "" if not chk["missing"] else
        "the missing entries are listed by `scaffold.py check`",
        "" if not chk["missing"] else "scaffold.py scaffold \"%s\"" % root)


# --- THE SWEEP (reorganize-directory 3) ------------------------------------
#
# The user asked for "sandbox/ if it can't tell", and the measurement that
# sets the limit is one line of a real probe run: `manuscript FINAL v3.docx`
# classifies as `ask`. A rule that swept every uncertain entry into sandbox/
# would move the paper into the one folder in the tree that nothing reads and
# then report success - the folder would look tidy and the manuscript would
# be gone from the engine's view entirely.
#
# So the sweep takes ONE tier. `unknown` is the only tier that means "it
# cannot tell": every other tier means the engine has an opinion it is
# declining to act on, which is a question and must stay one.
SWEEP_DEST = "sandbox/unsorted"
SWEEP_MANIFEST = "WHERE-THESE-CAME-FROM.md"
SWEEP_MANIFEST_HEAD = """# Where these came from

Every file here was moved by `scaffold.py adopt --sweep-unknown` because no
rule matched it and nothing inside it said what it was. **Nothing was
deleted, nothing was renamed, and nothing was read.** The original path of
each one is below, with the engine's own reason.

`sandbox/` is the one folder in this project that no engine reads, so
anything here is out of the paper's way and is also invisible to every check.
Move a file back the moment you know what it is.

| moved on | from | why it could not be placed |
|---|---|---|
"""


def _manuscript_shaped(root: str) -> set:
    """Relative paths `manuscript.py strays` calls `unexplained`.

    Exempt from the sweep whatever tier they are in. `strays` already knows
    what a manuscript-shaped document is and walks the same tree; two
    commands disagreeing about a `.docx` is the case that loses a paper.
    Imported lazily and defensively - an engine that cannot be loaded must
    make the sweep MORE careful, never less, so a failure here exempts
    every document rather than none.
    """
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import manuscript  # noqa: E402  (lazy on purpose - see docstring)
        res = manuscript.strays(root)
    except Exception:
        return {"*"}
    return {f["rel"] for f in res.get("findings", [])
            if f["kind"] == "unexplained"}


def sweepable(entry: dict, exempt: set) -> tuple[bool, str]:
    """Can this entry go to sandbox/unsorted/, and if not, why not.

    Two gates and an exemption, and the second gate is the one that is easy
    to leave out: `_classify_dir` returns `unknown` in two different
    situations - no name match and nothing inside speaks (a genuine shrug),
    and no name match but the contents look like data (an opinion). Only the
    first is swept, so a tier is not enough: it gates on `unknown` AND an
    empty proposal.
    """
    if entry.get("confidence") != "unknown":
        return (False, "%s is a tier the engine has an opinion in; a question "
                       "with an answer is not a shrug" % entry["confidence"])
    if entry.get("proposal"):
        return (False, "it proposes %s, so it is not `cannot tell` - it is an "
                       "answer nobody has said yes to yet" % entry["proposal"])
    if "*" in exempt:
        return (False, "the document reader could not be run, so nothing is "
                       "swept this run - a sweep that cannot check for a "
                       "manuscript does not run")
    if entry["path"] in exempt:
        return (False, "`manuscript.py strays` calls this an unexplained "
                       "document, and a manuscript-shaped file is never "
                       "swept whatever its tier")
    return (True, "")


# --- FLOAT ORDER (reorganize-directory 5.2) ---------------------------------
#
# Nothing in this toolkit took a set of loose figure files and produced a
# FLOAT SET IN AN ORDER. Measured 2026-09-20: `Figure 2 final.png`,
# `fig1_old.png` and `Figure_3_v2 (1).png` all classified identically as an
# image, and nothing noticed that they are numbered 1, 2 and 3, that two of
# them are superseded versions, or that no `Fig01/` folder exists to hold any
# of them.
#
# This PROPOSES. Five rules, four of them refusals:
#
#   1. it never creates a float folder and never renumbers anything. `float
#      new` and `float renumber` do that and they own the caption rewrite; a
#      second writer of plan/captions.md is a second answer to WHICH caption
#      is Figure 2;
#   2. a filename number is evidence, never an answer. `fig1_old.png` parses
#      to Figure 1 and is almost certainly not Figure 1 any more - the word
#      `old` is worth more than the digit, and both are reported;
#   3. two files parsing to one label are always a question, never a
#      resolution;
#   4. filename order does not overrule PROSE order - floats are numbered in
#      order of first mention, which is a fact about the manuscript, and a
#      filename is a fact about whoever saved the file;
#   5. it never reads inside a file. "Is this the same figure as that one" is
#      not answerable from bytes, and guessing would be worse than asking.

FLOAT_NAME_RE = re.compile(
    r"(?:^|[^a-z])(fig(?:ure)?|tab(?:le)?)[\s._\-]*(s?)[\s._\-]*(\d{1,3})"
    r"(?![0-9])", re.IGNORECASE)

# Words in a filename that say the file is not the current version. They are
# evidence and never a verdict - rule 2 - so they are reported beside the
# number rather than used to drop the file.
SUPERSEDED_WORDS = ("old", "prev", "previous", "draft", "backup", "copy",
                    "superseded", "deprecated", "v1", "v2", "v3", "orig",
                    "original")
FLOAT_CANDIDATE_EXTS = (".png", ".jpg", ".jpeg", ".tif", ".tiff", ".pdf",
                        ".svg", ".eps", ".gif", ".bmp", ".csv", ".xlsx",
                        ".xls", ".docx", ".pptx")


def parse_float_name(name: str) -> dict | None:
    """What float, if any, a filename claims to be.

    Deliberately narrow. `image_004.tif` and `run_data_2026_03_11.csv` carry
    numbers and claim nothing, and a parser that read them as floats would
    propose an order for every file in a data folder.
    """
    stem = os.path.splitext(os.path.basename(name))[0]
    m = FLOAT_NAME_RE.search(stem)
    if not m:
        return None
    kind = "figure" if m.group(1).lower().startswith("fig") else "table"
    supp = bool(m.group(2))
    number = int(m.group(3))
    low = stem.lower()
    marks = [w for w in SUPERSEDED_WORDS
             if re.search(r"(?:^|[^a-z0-9])%s(?:[^a-z0-9]|$)" % w, low)]
    return {"kind": kind, "number": number, "supplementary": supp,
            "label": "%s %s%d" % ("Figure" if kind == "figure" else "Table",
                                  "S" if supp else "", number),
            "version_marks": marks}


def float_order(root: str, depth: int = 3) -> dict:
    """Every file whose NAME claims to be a float, and what that set implies.

    Proposals only. It creates nothing, renames nothing and writes nothing.
    """
    res: dict = {"path": os.path.abspath(root), "exists": os.path.isdir(root),
                 "candidates": [], "version_groups": [], "gaps": [],
                 "duplicates": [], "existing_folders": [],
                 "prose_order": [], "filename_order": [],
                 "disagrees_with_prose": [], "did_not_run": "",
                 "note": "", "truncated": False}
    if not res["exists"]:
        return res

    res["existing_folders"] = [f["label"] for f in list_float_dirs(root)]

    known = _manifest_paths(root)
    seen = 0
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = os.path.relpath(dirpath, root).replace("\\", "/")
        if rel_dir == ".":
            rel_dir = ""
            dirnames[:] = [d for d in dirnames
                           if d not in known or d in ("plan", "data")]
        if rel_dir.split("/")[0] in ("obsolete", "sandbox"):
            dirnames[:] = []
            continue
        if rel_dir.count("/") + 1 > depth:
            dirnames[:] = []
        for name in sorted(filenames):
            if os.path.splitext(name)[1].lower() not in FLOAT_CANDIDATE_EXTS:
                continue
            if _is_noise(name, False):
                continue
            parsed = parse_float_name(name)
            if parsed is None:
                continue
            if seen >= DEPTH_WALK_CAP:
                res["truncated"] = True
                break
            seen += 1
            rel = (rel_dir + "/" + name) if rel_dir else name
            res["candidates"].append({
                "path": rel, "name": name,
                "in_float_folder": rel_dir.startswith("plan/"),
                **parsed,
                "folder_exists": parsed["label"] in res["existing_folders"]})

    by_label: dict[str, list[dict]] = {}
    for c in res["candidates"]:
        by_label.setdefault(c["label"], []).append(c)
    for label, group in sorted(by_label.items()):
        if len(group) > 1:
            res["version_groups"].append({
                "label": label, "files": [g["path"] for g in group],
                "marks": sorted({m for g in group for m in g["version_marks"]}),
                "why": ("%d files claim to be %s. Which one reaches the build "
                        "must never be the order the disk happens to list "
                        "them in%s" % (len(group), label,
                                       "" if not any(g["version_marks"]
                                                     for g in group)
                                       else " - and at least one of them says "
                                            "in its own name that it is not "
                                            "current"))})
            res["duplicates"].append(label)

    for kind in ("figure", "table"):
        for supp in (False, True):
            nums = sorted({c["number"] for c in res["candidates"]
                           if c["kind"] == kind and c["supplementary"] == supp})
            if not nums:
                continue
            missing = [n for n in range(1, max(nums) + 1) if n not in nums]
            for n in missing:
                res["gaps"].append(
                    "%s %s%d - nothing on disk claims to be it"
                    % ("Figure" if kind == "figure" else "Table",
                       "S" if supp else "", n))
    res["filename_order"] = [lab for lab, _ in sorted(
        by_label.items(),
        key=lambda kv: (kv[1][0]["kind"] != "figure",
                        kv[1][0]["supplementary"], kv[1][0]["number"]))]

    # Rule 4. The prose is right and the filenames are not - when there IS
    # prose. `crossrefs` owns first-mention order; this reads it rather than
    # deriving a second one.
    cross = _crossrefs_for_float_order(root)
    if cross is None:
        res["did_not_run"] = (
            "prose.py could not be loaded, so filename order was not checked "
            "against the manuscript. Nothing here is a verdict.")
    elif cross.get("did_not_run"):
        res["note"] = (
            "There is no drafted prose in this project yet, so the order "
            "below is a GUESS from the filenames. The order of a paper's "
            "figures is decided by the order the paper mentions them, so "
            "until the sections exist, every order here is something the "
            "author has to confirm. Getting this right is not something the "
            "tool can do by itself before the paper is written.")
    else:
        # Sorted by WHERE the first mention is, not by the order the
        # captions were declared in. The two are the same on a correct
        # manuscript and different on exactly the one this command exists
        # to report.
        res["prose_order"] = list(cross.get("mention_order") or [])
        shared = [lab for lab in res["prose_order"]
                  if lab in set(res["filename_order"])]
        shared_fn = [lab for lab in res["filename_order"] if lab in
                     set(res["prose_order"])]
        if shared != shared_fn:
            res["disagrees_with_prose"] = [
                "the prose mentions them %s; the filenames number them %s. "
                "The PROSE is right - floats are numbered in order of first "
                "mention, and a filename is a fact about whoever saved the "
                "file" % (", ".join(shared), ", ".join(shared_fn))]
    return res


def _crossrefs_for_float_order(root: str):
    """`prose.py crossrefs` over this project, or None if it cannot be run."""
    try:
        spec = importlib.util.spec_from_file_location(
            "prose_for_float_order",
            os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "prose.py"))
        if spec is None or spec.loader is None:
            return None
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod.crossrefs(root)
    except Exception:
        return None



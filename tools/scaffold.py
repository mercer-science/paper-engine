"""
scaffold.py - create the universal scientific-paper project structure.

Every project under Research/<PI> - <Field>/Projects/ gets the same shape, so
every later skill can assume where things live: plan/captions.md is always the
caption source of truth, data/analysis/analysis.md always holds the
numbers, plan/outline.md is always one line per paragraph.

Never overwrites. Re-running on a scaffolded project reports "already set up"
and restores anything that has since gone missing, which makes it safe to run
against a folder that already has work in it.

Usage:
  python scaffold.py scaffold "path/to/My Project" --title "..." --journal "JACS"
  python scaffold.py scaffold "path/to/My Project" --figures 4 --tables 2
  python scaffold.py scaffold "path/to/My Project" --dry-run
  python scaffold.py check "path/to/My Project"
  python scaffold.py tree "path/to/My Project"
  python scaffold.py github-offer "path/to/My Project" [--decline]

  python scaffold.py mock-floats "path/to/My Project" --bundle mock.json

  python scaffold.py float list "path/to/My Project"
  python scaffold.py float new "path/to/My Project" --figure --slug yield
  python scaffold.py float renumber "path/to/My Project" --from 3 --to 2
  python scaffold.py float migrate "path/to/My Project"
"""


def adopt(root: str, values: dict, dry_run: bool = False,
          apply_moves: bool = False, paper_kind: str = "research",
          expects_data: str | None = None, rnd: int = 1,
          depth: int = 1, sweep_unknown: bool = False) -> dict:
    """Scaffold what is missing, then propose a home for everything else.

    The order matters: the structure is created first, so a proposal can name
    a destination that exists. `--apply` then moves only the `clear` ones. A
    folder that has been worked in for months is the case this is for, and in
    that folder every judgement call belongs to its owner.
    """
    scaf = scaffold(root, values, dry_run=dry_run, n_figures=None,
                    n_tables=None, rnd=rnd, paper_kind=paper_kind,
                    expects_data=expects_data)
    expects = scaf["expects_data"]
    _, empty_dropped = expects_data_drops(expects)
    dropped = set(empty_dropped) | set(
        REVIEW_EMPTY_DROPS if paper_kind == "review" else ())

    res = {"path": os.path.abspath(root), "scaffold": scaf,
           "extras": [], "moved": [], "conflicts": [], "errors": [],
           "swept": [], "not_swept": [],
           "dry_run": dry_run, "applied": apply_moves,
           "depth": max(1, int(depth or 1)), "sweep": bool(sweep_unknown),
           "truncated": False}

    seen = survey(root, include_recorded=True, depth=depth)
    res["truncated"] = seen.get("truncated", False)
    res["collisions"] = seen.get("collisions", [])
    exempt = _manuscript_shaped(root) if sweep_unknown else set()
    for entry in seen["unexpected"]:
        e = dict(entry)
        dest = e["proposal"]
        # A proposal into a scope this project declared it does not have is
        # not a proposal. Saying so is the useful move: a CSV in a project
        # that expects no data means one of the two is wrong, and only the
        # user knows which.
        if dest and (dest in dropped
                     or (expects == "none" and dest.startswith("data/"))):
            e["confidence"] = "ask"
            e["why"] = ("%s - but this project declares expects_data: %s, so "
                        "%s does not exist. Either this is not what it looks "
                        "like, or the declaration is wrong."
                        % (e["why"], expects, dest))
            e["proposal"] = ""
            dest = ""
        e["action"] = ("move" if dest and e["confidence"] == "clear"
                       else "keep" if e["confidence"] == "keep" else "ask")
        if sweep_unknown:
            ok, why_not = sweepable(e, exempt)
            if ok:
                e["action"] = "sweep"
                e["sweep_to"] = SWEEP_DEST
            elif e["confidence"] == "unknown" or e["path"] in exempt:
                # Reported, and reported with the reason. An exemption
                # nobody is told about is a sweep that looks arbitrary.
                res["not_swept"].append({"path": e["path"], "why": why_not})
        if e["action"] == "move":
            target = os.path.join(root, *dest.split("/"), e["path"])
            if os.path.exists(target):
                e["action"] = "conflict"
                e["why"] = ("%s already holds something called %s - two files "
                            "with one name, and only you know whether they "
                            "are the same file" % (dest, e["path"]))
                res["conflicts"].append(e)
        res["extras"].append(e)

    if apply_moves and not dry_run and sweep_unknown:
        _sweep(root, res)

    if apply_moves and not dry_run:
        for e in res["extras"]:
            if e["action"] != "move":
                continue
            src = os.path.join(root, e["path"])
            dest_dir = os.path.join(root, *e["proposal"].split("/"))
            try:
                os.makedirs(dest_dir, exist_ok=True)
                shutil.move(src, os.path.join(dest_dir, e["path"]))
            except OSError as exc:
                e["action"] = "failed"
                res["errors"].append("%s -> %s: %s"
                                     % (e["path"], e["proposal"], exc))
                continue
            res["moved"].append({"from": e["path"],
                                 "to": e["proposal"] + "/" + e["path"]})
    return res


def _sweep(root: str, res: dict) -> None:
    """Move the shrugs into sandbox/unsorted/, and write the manifest.

    The manifest IS the product. A move nobody can reverse is a deletion
    with extra steps, and rule 1 of `setup-project-directory.md` 13.3 is
    that this command never deletes. It APPENDS - a second run adds rows
    rather than replacing the first run's record of where things were.
    """
    dest_dir = os.path.join(root, *SWEEP_DEST.split("/"))
    rows: list[str] = []
    swept_dirs: list[str] = []
    # Shallowest first, so a directory is swept before anything inside it is
    # considered. A folder moves WHOLE and takes its contents with it; the
    # first version of this moved `misc/` and then tried to move
    # `misc/another.qqq` from a path that no longer existed, and reported
    # three errors for one correct move.
    for e in sorted((x for x in res["extras"] if x.get("action") == "sweep"),
                    key=lambda x: x["path"].count("/")):
        if any(e["path"].startswith(d + "/") for d in swept_dirs):
            e["action"] = "swept_with_parent"
            continue
        src = os.path.join(root, *e["path"].split("/"))
        leaf = os.path.basename(e["path"])
        target = os.path.join(dest_dir, leaf)
        if os.path.exists(target):
            e["action"] = "conflict"
            e["why"] = ("%s already holds something called %s - two files "
                        "with one name, and only you know whether they are "
                        "the same file" % (SWEEP_DEST, leaf))
            res["conflicts"].append(e)
            continue
        try:
            os.makedirs(dest_dir, exist_ok=True)
            shutil.move(src, target)
        except OSError as exc:
            e["action"] = "failed"
            res["errors"].append("%s -> %s: %s" % (e["path"], SWEEP_DEST, exc))
            continue
        if os.path.isdir(target):
            swept_dirs.append(e["path"])
        res["swept"].append({"from": e["path"],
                             "to": SWEEP_DEST + "/" + leaf,
                             "why": e["why"]})
        rows.append("| %s | `%s` | %s |"
                    % (datetime.date.today().isoformat(), e["path"],
                       e["why"]))
    if not rows:
        return
    manifest = os.path.join(dest_dir, SWEEP_MANIFEST)
    if not os.path.isfile(manifest):
        with open(manifest, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(SWEEP_MANIFEST_HEAD)
    with open(manifest, "a", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(rows) + "\n")



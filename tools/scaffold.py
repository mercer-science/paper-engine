# ---------------------------------------------------------------------------
# resources/ -> methods_facts.yml, the facility prefill
# ---------------------------------------------------------------------------
#
# specs/setup-project-directory.md 10, and specs/orchestration.md 4 owns the
# folder. Three properties, and each one is the whole point:
#
#   1. COMMENTED, so nothing is asserted. The file reads as "here is what this
#      instrument usually does", not "here is what you did".
#   2. SOURCED, in the comment. A wrong default is traceable to the line in
#      resources/instruments.md that has to be corrected once for everybody.
#   3. REVERSIBLE BY DELETION. Removing the block loses nothing, because
#      nothing else reads it.
#
# Offered, never automatic. The trigger is what the user SAID about technique,
# not the project's field: the field template already ships the right shape of
# methods_facts.yml, and a project whose methods are not decided should not
# acquire a block for an instrument it will never touch.

# The layer is IN the marker (lab-resource-pack 4.2): a prefilled detector
# model that a member has to check is one they cannot check without knowing
# whose it is. `pack:` and `drop-zone:` are the two layers that can write one.
#
# The FILE is in the marker too, since 2026-09-28 (methods-notebook 2): a
# pack's `software.md` is read by the same parser and prefilled the same way,
# and a member checking a value has to know which of the two files to correct.
PREFILL_MARKER = ("# --- prefilled from %s:%s (%s), %s ---")
PREFILL_FILES = ("instruments.md", "software.md")
# GREEDY, and anchored on the date - an instrument name has parentheses in it
# (`Helios 5 UX (dual-beam SEM/FIB)`), so a non-greedy `\((.+?)\)` stops at the
# inner one and the name never matches the block it came from. Measured: the
# marker was written correctly and the re-run wrote the whole block again.
#
# The layer prefix is OPTIONAL and `resources/` is still accepted, forever.
# Every project scaffolded before the layers existed carries
# `prefilled from resources/instruments.md (...)` on disk, and that marker is
# the ONLY thing stopping a re-run writing the block a second time. A
# migration would have to touch every project that exists; reading both costs
# one optional group. Same reasoning as `retired_section_path()` reading two
# archive layouts.
PREFILL_MARKER_RE = re.compile(
    r"^#\s*---\s*prefilled from (?:[a-z-]+:|resources/)?"
    r"(?:instruments|software)\.md\s*"
    r"\((.+)\),\s*\d{4}-\d{2}-\d{2}", re.M)

# A key line inside an instrument block: `accelerating_voltage_kV: 5`.
#
# Capitals matter, and this is item 54 in its second home: the keys that carry
# UNITS are exactly the ones that have capitals - accelerating_voltage_kV,
# beam_current_nA, total_dose_e_per_A2, flow_mL_min. A lowercase-only class
# silently drops every setting that changes a result. Measured on a fixture
# block naming seven keys: five were written.
RES_KEY_RE = re.compile(r"^\s*([a-z][A-Za-z_0-9]*):\s*(.+?)\s*$")

# [TK] is the skeleton's own not-filled-in marker (resources/README.md). A
# value that is still [TK] is not a facility default, it is a blank, and
# writing it into a project would put the skeleton's placeholder one step
# closer to a manuscript.
TK_RE = re.compile(r"\[TK\b", re.I)

# A `##` section of resources/instruments.md that is documentation rather than
# an instrument says so with this marker. Explicit, because the alternative is
# a list of heading names in here that has to be kept in step with a file the
# group edits.
NOT_AN_INSTRUMENT = "<!-- not-an-instrument -->"
# Its counterpart in a pack's `software.md`: a technique whose package is not
# named is a section a paper cannot cite a program from.
NOT_A_PROGRAM = "<!-- not-a-program -->"
SKIP_MARKERS = (NOT_AN_INSTRUMENT, NOT_A_PROGRAM)


def _read_utf8(path: str) -> str:
    """A file, or "" - the same tolerance every reader in this toolkit has."""
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return ""


def resources_dir() -> str:
    """The toolkit's own `resources/`, beside `tools/`."""
    return os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "resources")


def parse_instrument_blocks(path: str) -> dict:
    """Instrument blocks and the keys each one names.

    Two forms are read, and the difference matters. A fenced ```yaml block
    inside an instrument's section is the machine-readable half and is
    unambiguous. Failing that, bare `key: value` lines in the section are
    taken. What is NOT done is deriving keys from the prose bullets: "the
    manufacturer's city and country" is a sentence about what to record, not a
    record, and turning it into `instrument_city: the manufacturer's city`
    would put a placeholder into a methods section wearing the shape of a
    fact.

    A block that names no keys is reported as naming none, with what to do
    about it. Silence there would read as "this instrument has no settings".
    """
    out: dict = {"path": path, "present": os.path.isfile(path),
                 "blocks": [], "notes": []}
    if not out["present"]:
        # 10.4: absent is not an error. The folder ships with the toolkit, but
        # a checkout may predate it or the group may not have filled it in.
        out["notes"].append(
            "no resources/instruments.md - nothing is prefilled and that is "
            "not a scaffold defect")
        return out

    text = _read_utf8(path)
    current: dict | None = None
    in_fence, fence_lang = False, ""
    fenced: list[str] = []
    for line in text.splitlines():
        fence = re.match(r"^\s*```\s*([a-z]*)\s*$", line)
        if fence:
            if in_fence:
                if current is not None and fence_lang == "yaml":
                    current["fenced"].extend(fenced)
                in_fence, fence_lang, fenced = False, "", []
            else:
                in_fence, fence_lang, fenced = True, fence.group(1), []
            continue
        if in_fence:
            fenced.append(line)
            continue
        head = re.match(r"^(#+)\s+(.+?)\s*$", line)
        if head:
            if len(head.group(1)) == 2:
                current = {"name": head.group(2).strip(), "lines": [],
                           "fenced": [], "skip": False}
                out["blocks"].append(current)
            else:
                # A key has to sit directly under its `##` instrument
                # heading. Anything under a sub-heading is documentation - the
                # file's own "optional machine-readable half" section carries
                # a worked yaml example, and without this rule that example
                # was offered as an instrument called "The block, and why each
                # line is in it".
                current = None
            continue
        if current is not None:
            if any(m in line for m in SKIP_MARKERS):
                current["skip"] = True
            current["lines"].append(line)

    kept = []
    for block in out["blocks"]:
        name = block["name"]
        if block.get("skip"):
            # The section said so itself. Explicit beats a list of heading
            # names in here that has to be kept in step with the file.
            continue
        if TK_RE.search(name):
            out["notes"].append(
                f"{name!r} is still a [TK:] placeholder - skipped")
            continue
        keys: dict = {}
        for line in (block["fenced"] or block["lines"]):
            km = RES_KEY_RE.match(line)
            if not km:
                continue
            key, val = km.group(1), km.group(2).split("#", 1)[0].strip()
            val = val.strip('"').strip("'")
            if not val or TK_RE.search(val):
                continue
            keys[key] = val
        if not keys:
            out["notes"].append(
                f"the {name!r} block names no keys. Add a ```yaml block to "
                f"it in {os.path.basename(path)} - the prose bullets say what "
                f"to record, and a sentence about what to record is not a "
                f"record")
            continue
        kept.append({"name": name, "keys": keys})
    out["blocks"] = kept
    return out


# ---------------------------------------------------------------------------
# The layer merge (lab-resource-pack 4.2)
# ---------------------------------------------------------------------------
#
# Two layers can hold an `instruments.md`, and the narrower one wins:
#
#   pack       one lab, curated, versioned, travels by plugin
#   drop-zone  whoever holds this copy of the toolkit
#
# **The wider layer is still named in the output** when it loses a key, so a
# member can see that two sources disagreed rather than discovering it in
# copy-editing. A project's own `methods_facts.yml` outranks both and is
# handled where it always was, in `prefill`.

_LABPACK_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "labpack.py")


def _labpack():
    """labpack.py, loaded by path.

    Imported lazily rather than at module load: `scaffold.py` is the engine
    every other one leans on, and a resolver that reaches the filesystem
    should not run for a caller that only wants the manifest.
    """
    spec = importlib.util.spec_from_file_location("labpack_for_scaffold",
                                                  _LABPACK_PATH)
    if spec is None or spec.loader is None:   # pragma: no cover - install bug
        raise ImportError(f"cannot load {_LABPACK_PATH}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def instrument_layers(resources: str = "",
                      filename: str = "instruments.md") -> list:
    """Every layer that could hold an `instruments.md`, narrowest LAST.

    Or a `software.md`: the same two layers and the same merge, over the file
    name rather than copied (methods-notebook 2.2).

    Narrowest last so a plain dict update leaves the narrowest value in place,
    which is the one line of this that a reader has to trust.

    An explicit `--resources` folder replaces the drop-zone ladder rather than
    joining it: a caller who named a folder meant that folder, and quietly
    merging three others into it is the surprise this toolkit exists to avoid.
    """
    lp = _labpack()
    layers = []
    if resources:
        layers.append({"layer": "drop-zone", "label": "drop-zone",
                       "path": os.path.join(resources, filename)})
    else:
        for root in reversed(lp.resource_roots()):
            layers.append({"layer": "drop-zone",
                           "label": f"drop-zone ({root['source']})",
                           "path": os.path.join(root["path"], filename)})
    pack = lp.find_pack()
    if pack.get("path"):
        layers.append({"layer": "pack",
                       "label": f"pack ({pack.get('display_name') or 'lab'})",
                       "path": os.path.join(pack["path"], filename),
                       "pack": pack})
    return layers


def merged_instrument_blocks(resources: str = "",
                             filename: str = "instruments.md") -> dict:
    """One block list, merged across the layers, each key knowing its layer.

    The merge is per KEY rather than per block. Two layers describing the same
    instrument usually agree about the model and disagree about one setting,
    and dropping the whole wider block because the narrower one exists would
    lose the keys only the wider one names - which are, reliably, the ones
    somebody took the trouble to write down locally.
    """
    out: dict = {"blocks": [], "notes": [], "layers": [], "sources": []}
    merged: dict = {}
    skip_marker = (NOT_A_PROGRAM if filename == "software.md"
                   else NOT_AN_INSTRUMENT)
    for layer in instrument_layers(resources, filename):
        parsed = parse_instrument_blocks(layer["path"])
        out["layers"].append({"layer": layer["layer"], "label": layer["label"],
                              "path": layer["path"],
                              "present": parsed["present"],
                              "blocks": len(parsed["blocks"])})
        if parsed["present"]:
            out["sources"].append(layer["path"])
        # A layer with NO machine-readable half anywhere is one fact, not one
        # per block. Measured on a real pack: eleven `##` blocks, none with a
        # yaml half, produced eleven identical notes and offered nothing -
        # and several of the eleven were documentation sections that were
        # never instruments. Eleven lines saying the same thing is a check
        # people learn to scroll past, which is how a real one gets missed.
        # Below the threshold each block is still named, because then the
        # note IS the actionable thing.
        keyless = [re.sub(r"^the '(.*)' block names no keys.*$", r"\1", n)
                   for n in parsed["notes"] if "names no keys" in n]
        collapse = len(keyless) > 3
        for note in parsed["notes"]:
            if not parsed["present"]:
                continue
            if collapse and "names no keys" in note:
                continue
            out["notes"].append(f"{layer['label']}: {note}")
        if collapse:
            shown = ", ".join(repr(n) for n in keyless[:3])
            out["notes"].append(
                f"{layer['label']}: {len(keyless)} of its blocks name no "
                f"keys ({shown}, ...), so none of them can be prefilled. "
                f"They are prose, which is what a person reads - add a "
                f"```yaml block to the ones that are instruments, and mark "
                f"the ones that are documentation with "
                f"{skip_marker}")
        for block in parsed["blocks"]:
            slot = merged.setdefault(block["name"],
                                     {"name": block["name"], "keys": {},
                                      "layer": layer["layer"],
                                      "label": layer["label"],
                                      "key_layers": {}})
            for key, val in block["keys"].items():
                previous = slot["keys"].get(key)
                if previous is not None and previous != val:
                    out["notes"].append(
                        f"{block['name']}: {key} is {val!r} in "
                        f"{layer['label']} and {previous!r} in "
                        f"{slot['key_layers'][key]}. The narrower layer wins; "
                        f"the wider one is named here so you can see they "
                        f"disagreed")
                slot["keys"][key] = val
                slot["key_layers"][key] = layer["label"]
            slot["layer"] = layer["layer"]
            slot["label"] = layer["label"]
    out["blocks"] = [merged[name] for name in sorted(merged)]
    if not out["sources"] and filename == "instruments.md":
        # Said for the instrument file only. A pack with no software file is
        # the ordinary case, and a note about its absence on every listing
        # is a line people learn to scroll past.
        out["notes"].append(
            "no instruments.md in any layer - nothing is prefilled and that "
            "is not a scaffold defect")
    return out



def confirmed_keys(text: str) -> set:
    """Keys in methods_facts.yml that already carry a real value.

    A confirmed value outranks a facility default, always (10.5). Only an
    UNCOMMENTED line with something after the colon counts - which is the same
    rule manuscript.py's `_recorded_fields` applies, and the reason a
    commented prefill counts as missing everywhere downstream.
    """
    out = set()
    for m in re.finditer(r"^[ \t]*([a-z][A-Za-z_0-9]*):[ \t]*(.*)$",
                         text, re.M):
        val = m.group(2).split("#", 1)[0].strip().strip('"').strip("'")
        if val and not val.startswith("{") and not val.startswith("["):
            out.add(m.group(1))
    return out


def outside_prefilled_blocks(text: str) -> str:
    """The file with every prefilled block cut out.

    A block runs from its marker line to the first blank line, which is how
    `prefill` writes one. Item 161: a key confirmed INSIDE one instrument's
    block is a fact about that instrument, and reading the whole file made it
    count as recorded for every other instrument prefilled later. Only what
    the project records outside every block outranks a facility default.
    """
    kept: list = []
    inside = False
    for line in text.splitlines():
        if PREFILL_MARKER_RE.match(line):
            inside = True
            continue
        if inside:
            if not line.strip():
                inside = False
            continue
        kept.append(line)
    return "\n".join(kept)


def prefilled_blocks(text: str) -> list[str]:
    """Which instrument blocks have already been prefilled into this file."""
    return [m.group(1) for m in PREFILL_MARKER_RE.finditer(text)]


def render_prefill(name: str, keys: dict, skipped: dict,
                   layer: str = "drop-zone", label: str = "",
                   key_layers: dict | None = None,
                   filename: str = "instruments.md") -> str:
    lines = [PREFILL_MARKER % (layer, filename, name,
                               datetime.date.today().isoformat()),
             # NOT `# source: ...`. `PREFILL_KEY_RE` in manuscript.py reads
             # any `# <lowercase>: <value>` under this marker as a prefilled
             # METHODS KEY, so that spelling put a field called `source` into
             # the unconfirmed list of every project. The leading `--` keeps
             # it out of that class while reading as part of the marker.
             f"# -- source: {label or layer} --",
             "# Confirm or correct each line, then remove the leading '#'. A",
             "# commented value counts as MISSING - manuscript.py completeness",
             "# says so, and the methods paragraph will carry a "
             "**[FLAG: ...]**",
             "# rather than this number."]
    if filename == "software.md":
        # No version key exists, on purpose: the version is chosen per
        # dataset, so a pack value would be right for somebody else's data.
        # Starts `# --` so PREFILL_KEY_RE never reads it as a key.
        lines.append("# -- no version here: the pack records none. Write the "
                     "version this project ran --")
    key_layers = key_layers or {}
    for key, val in keys.items():
        from_layer = key_layers.get(key, "")
        suffix = (f"   # from {from_layer}"
                  if from_layer and from_layer != label else "")
        lines.append(f"# {key}: {val}{suffix}")
    for key, val in skipped.items():
        lines.append(f"# (not written) {key}: this project already records "
                     f"{val!r}")
    return "\n".join(lines) + "\n"


def prefill(root: str, wanted: list[str], dry_run: bool = False,
            resources: str = "", software: list[str] | None = None) -> dict:
    """Write commented facility defaults into data/methods_facts.yml.

    `wanted` names instrument blocks and `software` names program blocks
    from the pack's `software.md` (methods-notebook 2). Both are written the
    same way: commented out, sourced, counted as missing until confirmed.
    """
    parsed = merged_instrument_blocks(resources)
    progs = merged_instrument_blocks(resources, "software.md")
    res = {"project": os.path.abspath(root),
           "source": ", ".join(parsed["sources"] + progs["sources"])
                     or "(no layer holds one)",
           "layers": parsed["layers"],
           "software_layers": progs["layers"],
           "available": [b["name"] for b in parsed["blocks"]],
           "available_software": [b["name"] for b in progs["blocks"]],
           "notes": list(parsed["notes"]) + list(progs["notes"]),
           "written": [], "skipped": [],
           "already": [], "unknown": [], "dry_run": dry_run}

    facts_path = os.path.join(root, "data", "methods_facts.yml")
    if not os.path.isfile(facts_path):
        res["notes"].append(
            "no data/methods_facts.yml in this project - scaffold it first")
        return res
    text = _read_utf8(facts_path)
    have = confirmed_keys(outside_prefilled_blocks(text))
    done = prefilled_blocks(text)

    by_name: dict[str, dict] = {b["name"]: {**b, "file": "instruments.md"}
                                for b in parsed["blocks"]}
    by_prog: dict[str, dict] = {b["name"]: {**b, "file": "software.md"}
                                for b in progs["blocks"]}
    requests: list[tuple[str, dict[str, dict]]] = (
        [(n, by_name) for n in wanted]
                + [(n, by_prog) for n in (software or [])])
    additions = []
    for name, table in requests:
        block = table.get(name)
        if block is None:
            # Named but not found. Reported rather than ignored: a typo in an
            # instrument name would otherwise look like a facility record that
            # has nothing in it.
            res["unknown"].append(name)
            continue
        if name in done:
            # The marker line is the key, so a re-run does not write it twice.
            res["already"].append(name)
            continue
        keys, skipped = {}, {}
        for key, val in block["keys"].items():
            if key in have:
                skipped[key] = val
            else:
                keys[key] = val
        if not keys:
            res["skipped"].append(
                {"block": name,
                 "why": "every key it names is already recorded in this "
                        "project, and a confirmed value outranks a facility "
                        "default"})
            continue
        additions.append(render_prefill(
            name, keys, skipped, layer=block.get("layer", "drop-zone"),
            label=block.get("label", ""),
            key_layers=block.get("key_layers"), filename=block["file"]))
        res["written"].append({"block": name, "keys": sorted(keys),
                               "file": block["file"],
                               "layer": block.get("layer", "drop-zone"),
                               "left_alone": sorted(skipped)})

    if additions and not dry_run:
        with open(facts_path, "a", encoding="utf-8", newline="\n") as fh:
            fh.write("\n\n" + "\n\n".join(additions))
    res["path"] = "data/methods_facts.yml"
    return res


def print_prefill(res: dict) -> None:
    for layer in res.get("layers") or []:
        state = (f"{layer['blocks']} block(s)" if layer["present"]
                 else "no instruments.md")
        print(f"  {layer['label']:28} {state}")
    print(f"{res['source']}")
    if res["available"]:
        print("  blocks available: " + ", ".join(res["available"]))
    if res.get("available_software"):
        print("  software available: "
              + ", ".join(res["available_software"]))
    for name in res["unknown"]:
        print(f"  UNKNOWN  {name!r} is not a block in this file")
    for w in res["written"]:
        verb = "would write" if res["dry_run"] else "wrote"
        print(f"  {verb} {len(w['keys'])} commented key(s) for {w['block']} "
              f"[{w.get('layer', 'drop-zone')}]: " + ", ".join(w["keys"]))
        if w["left_alone"]:
            print("    left alone (already recorded here): "
                  + ", ".join(w["left_alone"]))
    for name in res["already"]:
        print(f"  already prefilled: {name}")
    for s in res["skipped"]:
        print(f"  skipped {s['block']}: {s['why']}")
    for n in res["notes"]:
        print(f"  note: {n}")
    if res["written"]:
        print("\nEvery line is commented out and carries where it came from. A"
              "\ncommented value counts as MISSING until you delete the '#',"
              "\nso nothing here can reach a manuscript as a fact by accident.")


# ---------------------------------------------------------------------------
# harvest - the facts the instrument already wrote (item 46)
# ---------------------------------------------------------------------------
#
# `methods_facts.yml`'s own header used to open with the premise that let a
# whole round of flags through: *"the methods section is the one part of a
# paper that cannot be reconstructed from this folder, because the facts it
# needs never enter the folder at all: reagent lots, solvent grades,
# instrument parameters."*
#
# Two of those three are true. **Instrument parameters do enter the folder** -
# they are in every file the instrument writes. Measured on one real project:
# all 158 `.tif` files carry a Thermo/FEI acquisition block naming the
# microscope, the detector and its mode, the accelerating voltage, the beam
# current, the dwell time, the field width and the pixel size, to five
# significant figures. The round shipped `**[FLAG: author]**` asking a human
# for three of them, and the answer to one - *which microscope* - was
# **two** microscopes, which is the answer a person writing from memory is
# most likely to get wrong.
#
# That is item 22's rule failing in practice: a flag that survives into the
# manuscript is for a question only a person can answer, and "what voltage was
# this image taken at" is not one when the image says. Item 22 fixed it in
# prose, and its own note records "nothing in the engine enforces it"; one
# round later the same class of flag came back. So this is the thing behind
# the lookup branch of the flag test that is not the drafter remembering to
# look.
#
# THREE RULES, and each one is load-bearing:
#
#   * **A harvested value is recorded, so it is written UNCOMMENTED.** That is
#     the whole difference from `prefill`, which writes a facility default -
#     someone else's typical value - and comments it out so it counts as
#     missing until a human confirms it. Nobody has to confirm what the
#     instrument wrote about its own exposure.
#   * **A key whose files disagree is written as the disagreement**, never as
#     the majority. `instrument` on the project that found this is two
#     microscopes rather than one, and a methods section naming one of them
#     would be false. The written value names both with their counts, so the
#     drafter writes two microscopes because the file says two.
#   * **A value already recorded by hand is never touched.** Same rule as
#     `prefill`: a confirmed value outranks anything derived, and a harvest
#     that overwrote the operator's own note would be the engine deciding it
#     knows the bench better than the person who was standing at it.
#
# The per-file record goes to `data/instrument_metadata.json` and is the
# provenance: every value in the summary can be traced to the files that carry
# it, which is what makes "most of them, not all" checkable rather than a
# claim.

# Where a Thermo/FEI (formerly Philips/FEI) instrument puts its acquisition
# block. Three private TIFF tags are in use across generations of their
# software, and a file carries whichever one its acquisition program wrote.
FEI_TIFF_TAGS = (34682, 34680, 34683)

# The FEI ini `[Section] Key` pairs worth harvesting, mapped to the
# methods_facts.yml key each one answers, with the unit conversion that turns
# the instrument's SI into what a methods section says.
#
# Nothing is invented here: every entry names a key a scaffolded
# methods_facts.yml already has, or one whose name says its unit the way the
# rest of that file does.
# The fifth column is the KIND, and getting it wrong makes the harvest
# unreadable rather than wrong. A `set` field is a knob somebody turned - the
# microscope, the detector, the voltage - and its distinct values ARE the
# finding: two microscopes, two detector modes. A `per_image` field is
# measured afresh for every exposure, so a few hundred files legitimately
# carry dozens of distinct working distances, and listing them is not a
# methods fact. Those are
# summarised as a range over the files, with the per-file record carrying the
# exact number for anyone who needs one.
FEI_FIELDS: list[tuple] = [
    ("System", "SystemType", "instrument", None, "", "set"),
    ("Beam", "HV", "voltage_kV", 1e-3, "kV", "set"),
    ("EBeam", "BeamCurrent", "beam_current_pA", 1e12, "pA", "set"),
    ("EBeam", "WD", "working_distance_mm", 1e3, "mm", "per_image"),
    ("EBeam", "LensMode", "lens_mode", None, "", "set"),
    ("Scan", "Dwelltime", "dwell_time_us", 1e6, "us", "set"),
    ("Scan", "HorFieldsize", "field_width_um", 1e6, "um", "per_image"),
    ("Scan", "PixelWidth", "pixel_size_nm", 1e9, "nm", "per_image"),
    ("Detectors", "Name", "detector", None, "", "set"),
    ("Detectors", "Mode", "detector_mode", None, "", "set"),
    ("Image", "ResolutionX", "image_width_px", None, "px", "set"),
    ("Image", "ResolutionY", "image_height_px", None, "px", "set"),
    ("Vacuum", "UserMode", "vacuum_mode", None, "", "set"),
    ("Vacuum", "ChPressure", "chamber_pressure_Pa", None, "Pa", "per_image"),
]

FIELD_KIND = {f[2]: f[5] for f in FEI_FIELDS}
FIELD_UNIT = {f[2]: f[4] for f in FEI_FIELDS}

# How many distinct values of a `set` field are listed before the rest are
# counted rather than named. Nine microscopes is a finding; ninety is a
# miscategorised field, and the line says which it is either way.
MAX_LISTED_VALUES = 8

HARVEST_MARKER = ("# --- harvested from %d instrument file(s) by "
                  "`scaffold.py harvest` on %s ---")
HARVEST_MARKER_RE = re.compile(
    r"^#\s*---\s*harvested from (\d+) instrument file\(s\).*?---\s*$", re.M)

_TIFF_TYPE_SIZE = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 6: 1, 7: 1, 8: 2, 9: 4,
                   10: 8, 11: 4, 12: 8}


def read_fei_block(path: str) -> str:
    """The instrument's ini text out of one TIFF, or "".

    The tag is read out of IFD0 rather than the file being scanned for
    `[User]`, because a scan finds the string wherever it happens to be -
    including inside image data - and a value read from the wrong offset is
    reported with exactly the confidence of one read from the right offset.
    The tail scan is kept as an explicit fallback for the writers that append
    the block outside any tag, and it is reported as the weaker source.
    """
    try:
        with open(path, "rb") as fh:
            head = fh.read(8)
            if len(head) < 8 or head[:2] not in (b"II", b"MM"):
                return ""
            end = "<" if head[:2] == b"II" else ">"
            magic, ifd = struct.unpack(end + "HI", head[2:8])
            if magic != 42:
                # BigTIFF (magic 43) has a different IFD layout. Refused by
                # name rather than mis-parsed - the whole point of reading the
                # tag was not guessing at offsets.
                return ""
            fh.seek(ifd)
            count = struct.unpack(end + "H", fh.read(2))[0]
            entries = fh.read(count * 12)
            for i in range(count):
                tag, typ, n = struct.unpack(end + "HHI",
                                            entries[i * 12:i * 12 + 8])
                if tag not in FEI_TIFF_TAGS:
                    continue
                size = _TIFF_TYPE_SIZE.get(typ, 1) * n
                if size <= 4:
                    raw = entries[i * 12 + 8:i * 12 + 8 + size]
                else:
                    off = struct.unpack(end + "I",
                                        entries[i * 12 + 8:i * 12 + 12])[0]
                    fh.seek(off)
                    raw = fh.read(size)
                text = raw.decode("latin-1", "replace")
                if "[" in text:
                    return text
            # Fallback: the block appended past the image data.
            fh.seek(0, os.SEEK_END)
            size = fh.tell()
            fh.seek(max(0, size - 65536))
            tail = fh.read().decode("latin-1", "replace")
            i = tail.rfind("[User]")
            return tail[i:] if i >= 0 else ""
    except (OSError, struct.error):
        return ""


def parse_fei_ini(text: str) -> dict:
    """`[Section]` / `Key=Value` into {"Section.Key": "value"}."""
    out: dict = {}
    section = ""
    for line in text.splitlines():
        line = line.strip().strip("\x00")
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1].strip()
            continue
        if "=" in line and section:
            key, _, val = line.partition("=")
            val = val.strip()
            if val:
                out["%s.%s" % (section, key.strip())] = val
    return out


def _scaled(val: str, factor, unit: str) -> str:
    """The instrument's SI value in the unit the methods key names.

    A value that will not parse as a number is passed through untouched. It is
    a fact either way, and mangling it into `0` because the conversion assumed
    a float is the failure this whole module exists to prevent.
    """
    if factor is None:
        return val
    try:
        num = float(val) * factor
    except ValueError:
        return val
    # Enough figures to be the instrument's number rather than a rounding of
    # it, with the trailing zeros of the float representation dropped.
    text = ("%.6g" % num)
    return text + ((" " + unit) if unit and not text.endswith(unit) else "")


def harvest_instrument_files(root: str, subdir: str = "") -> dict:
    """Every acquisition block under `root`, as facts with their provenance.

    Reports `files_read` and `files_with_metadata` separately, always. "158 of
    158" and "12 of 158" are different findings and only one of them means the
    harvest covered the project - collapsing them into a fact count would let
    a run that read a tenth of the folder report a confident value.
    """
    base = os.path.join(root, subdir) if subdir else root
    res: dict = {"project": os.path.abspath(root),
                 "scanned": os.path.abspath(base),
                 "files_read": 0, "files_with_metadata": 0,
                 "facts": {}, "per_file": [], "notes": []}
    if not os.path.isdir(base):
        res["notes"].append("no such directory: %s" % base)
        return res

    values: dict = {}
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for name in sorted(filenames):
            if os.path.splitext(name)[1].lower() not in (".tif", ".tiff"):
                continue
            full = os.path.join(dirpath, name)
            res["files_read"] += 1
            ini = parse_fei_ini(read_fei_block(full))
            if not ini:
                continue
            res["files_with_metadata"] += 1
            rel = os.path.relpath(full, os.path.abspath(root))
            rec: dict = {"file": rel.replace(os.sep, "/")}
            for field in FEI_FIELDS:
                section, ikey, mkey, factor, unit = field[:5]
                raw = ini.get("%s.%s" % (section, ikey), "")
                if not raw:
                    continue
                val = _scaled(raw, factor, unit)
                rec[mkey] = val
                values.setdefault(mkey, {}).setdefault(val, []).append(
                    rec["file"])
            for stamp in ("User.Date", "User.Time"):
                if ini.get(stamp):
                    rec[stamp.split(".")[1].lower()] = ini[stamp]
            res["per_file"].append(rec)

    for mkey, byval in sorted(values.items()):
        ranked = sorted(byval.items(), key=lambda kv: (-len(kv[1]), kv[0]))
        entry: dict = {
            "kind": FIELD_KIND.get(mkey, "set"),
            "unit": FIELD_UNIT.get(mkey, ""),
            "distinct": len(ranked),
            "files": sum(len(f) for f in byval.values()),
            "values": [{"value": v, "files": len(f), "example": f[0]}
                       for v, f in ranked],
            "unanimous": len(ranked) == 1,
        }
        if entry["kind"] == "per_image" and len(ranked) > 1:
            entry["range"] = _numeric_range(byval)
        res["facts"][mkey] = entry
    if res["files_read"] and not res["files_with_metadata"]:
        res["notes"].append(
            "%d image file(s) read and none carries an acquisition block - "
            "either they were exported rather than saved by the instrument, "
            "or this instrument does not write one. Nothing was harvested and "
            "nothing about the methods is settled by that"
            % res["files_read"])
    return res


def _numeric_range(byval: dict) -> dict:
    """low / high / median over the files, for a value measured per image.

    Weighted by file, not by distinct value: a working distance held for 40
    exposures and one held for a single exposure are not equal evidence about
    what the session was, and a median over the distinct strings would say
    they are.
    """
    nums: list[float] = []
    unit = ""
    for val, files in byval.items():
        head = val.split(" ")[0]
        unit = unit or (val.split(" ", 1)[1] if " " in val else "")
        try:
            num = float(head)
        except ValueError:
            return {}
        nums.extend([num] * len(files))
    nums.sort()
    mid = len(nums) // 2
    median = nums[mid] if len(nums) % 2 else (nums[mid - 1] + nums[mid]) / 2
    return {"low": "%.6g" % nums[0], "high": "%.6g" % nums[-1],
            "median": "%.6g" % median, "unit": unit, "n": len(nums)}


def _fact_line(mkey: str, entry: dict) -> str:
    """One methods_facts.yml line for one harvested key."""
    vals = entry["values"]
    if entry["unanimous"]:
        return "%s: %s   # all %d file(s)" % (
            mkey, _yaml_scalar(vals[0]["value"]), vals[0]["files"])
    rng = entry.get("range")
    if rng:
        text = "%s-%s %s (median %s, %d files)" % (
            rng["low"], rng["high"], rng["unit"], rng["median"], rng["n"])
        return ("%s: %s   # measured per image; the exact value for each "
                "file is in the provenance file"
                % (mkey, _yaml_scalar(text)))
    # A knob whose files disagree. The disagreement IS the value: a methods
    # section naming one microscope on a project that used two is false, and
    # the majority is the most confident way to be false.
    shown = vals[:MAX_LISTED_VALUES]
    joined = "; ".join("%s (%d file%s)"
                       % (v["value"], v["files"],
                          "" if v["files"] == 1 else "s")
                       for v in shown)
    if len(vals) > len(shown):
        joined += "; and %d more - see the provenance file" % (
            len(vals) - len(shown))
    return "%s: %s   # %d distinct values across %d file(s)" % (
        mkey, _yaml_scalar(joined), entry["distinct"], entry["files"])


def render_harvest(facts: dict, n_files: int) -> str:
    """The block appended to methods_facts.yml. Uncommented, with counts.

    It goes in under one `instrument_metadata:` key rather than as loose
    top-level lines, for the reason every other writer in this toolkit keeps
    away from a name somebody else owns: a project that already writes
    `electron_microscopy: instrument:` by hand would otherwise acquire a
    second `instrument:` at a different level, and the two would be read as
    the same key by anything matching on the bare name.
    """
    lines = [HARVEST_MARKER % (n_files, datetime.date.today().isoformat()),
             "# Written by the INSTRUMENT, not by a person, so these are "
             "recorded values",
             "# and are NOT commented out - a `prefill` default is somebody "
             "else's",
             "# typical number and has to be confirmed; this is what this "
             "microscope",
             "# wrote about these exposures. Nothing here may become a "
             "[FLAG: author]:",
             "# the answer is on disk, and the per-file record proves it.",
             "#",
             "# THIS BLOCK IS REGENERATED by every `harvest` run, because "
             "the counts",
             "# move as more images arrive and a stale \"all 148 file(s)\" "
             "is worse than",
             "# no line at all. So do not correct a value in here - it will "
             "not survive.",
             "# Write the correction ANYWHERE ELSE in this file instead: a "
             "value a",
             "# person recorded outranks anything derived, and the harvest "
             "leaves it",
             "# alone and says so.",
             "instrument_metadata:",
             "  provenance: data/instrument_metadata.json",
             "  files: %d" % n_files]
    for mkey in sorted(facts):
        lines.append("  " + _fact_line(mkey, facts[mkey]))
    return "\n".join(lines) + "\n"


def _yaml_scalar(val: str) -> str:
    """Quote where the flat reader would otherwise mis-read it."""
    if val and re.fullmatch(r"[-+0-9A-Za-z_. ]+", val) and ":" not in val:
        return val
    return '"%s"' % val.replace('"', "'")


def strip_harvest_blocks(text: str) -> tuple[str, int]:
    """methods_facts.yml with every previous harvest block taken out.

    The block is REGENERATED on every harvest rather than skipped the way a
    `prefill` block is, because more images arrive and the counts move: a
    file that says "all 148 file(s)" after a run that read 158 is worse than
    one that says nothing, since it is a specific number and will be
    believed.

    That is exactly why the block must not be where a correction lives. A
    value a person wants to hold against the instrument goes ANYWHERE ELSE in
    the file, where this function cannot reach it and where the
    already-recorded test then leaves it alone - and the block's own header
    says so. Deciding which lines inside a regenerated block were hand-edited
    would mean the engine guessing at authorship of a line, which is the kind
    of guess this toolkit reports instead of making.
    """
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    removed, i = 0, 0
    while i < len(lines):
        if not HARVEST_MARKER_RE.match(lines[i].rstrip("\r\n") + "\n"):
            out.append(lines[i])
            i += 1
            continue
        removed += 1
        i += 1
        while i < len(lines):
            line = lines[i]
            bare = line.strip()
            if (not bare or bare.startswith("#")
                    or line[:1] in (" ", "\t")
                    or bare.startswith("instrument_metadata:")):
                i += 1
                continue
            break
        # The blank line that separated the block from what came before it.
        while out and not out[-1].strip():
            out.pop()
    return "".join(out), removed


def harvest(root: str, subdir: str = "", dry_run: bool = False) -> dict:
    """Read the instruments' own record, and write what nobody recorded."""
    res = harvest_instrument_files(root, subdir)
    res["written"] = []
    res["left_alone"] = []
    res["dry_run"] = dry_run

    prov_rel = os.path.join("data", "instrument_metadata.json")
    prov_path = os.path.join(root, prov_rel)
    res["provenance"] = prov_rel.replace(os.sep, "/")

    facts_path = os.path.join(root, "data", "methods_facts.yml")
    if not os.path.isfile(facts_path):
        res["notes"].append(
            "no data/methods_facts.yml in this project - nothing was written "
            "there. The per-file record is still the answer to every question "
            "the harvest covers")
    text = _read_utf8(facts_path)
    # `confirmed_keys` is prefill's test and is deliberately narrow - a list
    # or a mapping is not a confirmed scalar there. Here it has to be wider:
    # a hand-written `beam_current_pA: [50, 86]` IS somebody recording the
    # answer, and re-writing it from the files would be the engine deciding it
    # knows the bench better than the person who was standing at it.
    #
    # An EMPTY quoted string is not a record, and it is the shape the question
    # actually takes on disk: `instrument: ""   # not stated in the outline`
    # is a person saying they do not know. Reading it as "already recorded"
    # would leave the one key this whole command exists to answer unanswered,
    # while reporting that it had been left alone out of respect.
    # A previous harvest's own block is not evidence that a person recorded
    # anything, so it is taken out before the question is asked. Everything
    # else in the file - including a line a person added to overrule the
    # instrument - is.
    hand_written, res["previous_blocks"] = strip_harvest_blocks(text)
    have = set(confirmed_keys(hand_written))
    for m in re.finditer(r"^[ \t]*([a-z][A-Za-z_0-9]*):[ \t]*(\S.*)$",
                         hand_written, re.M):
        val = m.group(2).split("#", 1)[0].strip()
        if val.startswith("[") or val.startswith("{"):
            have.add(m.group(1))
        elif val.strip('"').strip("'").strip():
            have.add(m.group(1))

    keep = {k: v for k, v in res["facts"].items() if k not in have}
    res["left_alone"] = sorted(k for k in res["facts"] if k in have)

    if not res["per_file"]:
        return res
    if dry_run:
        res["written"] = sorted(keep)
        return res

    # A trimmed project may have no `data/` at all. Creating one is a side
    # effect, so it is reported rather than done quietly - the same rule
    # `init` follows about not growing a float pipeline nobody asked for. It
    # can only happen when there is a real record to put in it, because the
    # empty case returned above.
    if not os.path.isdir(os.path.dirname(prov_path)):
        res["notes"].append(
            "this project had no data/ folder; one was created to hold the "
            "per-file record")
    os.makedirs(os.path.dirname(prov_path), exist_ok=True)
    with open(prov_path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({"harvested": datetime.date.today().isoformat(),
                   "scanned": res["scanned"],
                   "files_read": res["files_read"],
                   "files_with_metadata": res["files_with_metadata"],
                   "facts": res["facts"],
                   "per_file": res["per_file"]}, fh, indent=2)

    if keep and os.path.isfile(facts_path):
        body = hand_written.rstrip("\n")
        with open(facts_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body + "\n\n\n"
                     + render_harvest(keep, res["files_with_metadata"]))
        res["written"] = sorted(keep)
    return res


def print_harvest(res: dict) -> None:
    print("%s" % res["scanned"])
    print("  %d image file(s) read, %d carrying an acquisition block"
          % (res["files_read"], res["files_with_metadata"]))
    for mkey in sorted(res["facts"]):
        entry = res["facts"][mkey]
        rng = entry.get("range")
        if rng:
            print("    %-24s %s-%s %s   (median %s, %d file(s), measured per "
                  "image)"
                  % (mkey, rng["low"], rng["high"], rng["unit"],
                     rng["median"], rng["n"]))
            continue
        shown = entry["values"][:MAX_LISTED_VALUES]
        for i, v in enumerate(shown):
            print("    %-24s %-34s %d file(s)"
                  % (mkey if i == 0 else "", v["value"], v["files"]))
        if entry["distinct"] > len(shown):
            print("    %-24s and %d more distinct value(s) - see %s"
                  % ("", entry["distinct"] - len(shown), res["provenance"]))
        if not entry["unanimous"]:
            print("    %-24s ^ %d DISTINCT VALUES - written as the "
                  "disagreement, never as the majority"
                  % ("", entry["distinct"]))
    if res.get("written"):
        verb = "would write" if res.get("dry_run") else "wrote"
        print("\n  %s %d recorded value(s) into data/methods_facts.yml: %s"
              % (verb, len(res["written"]), ", ".join(res["written"])))
    if res.get("left_alone"):
        print("  left alone (already recorded by hand, which outranks this): "
              + ", ".join(res["left_alone"]))
    if res.get("per_file") and not res.get("dry_run"):
        print("  per-file provenance: %s (%d record(s))"
              % (res["provenance"], len(res["per_file"])))
    for n in res.get("notes", []):
        print("  note: %s" % n)


def tree(root: str, prefix: str = "", rel: str = "") -> list[str]:
    try:
        names = sorted(os.listdir(os.path.join(root, rel)))
    except OSError:
        return []
    names = [n for n in names if n not in _TREE_SKIP and n != ".gitkeep"]
    lines = []
    for i, name in enumerate(names):
        last = i == len(names) - 1
        child_rel = f"{rel}/{name}" if rel else name
        full = os.path.join(root, child_rel)
        is_dir = os.path.isdir(full)
        note = _TREE_NOTES.get(child_rel, "")
        label = name + ("/" if is_dir else "")
        lines.append(f"{prefix}{'`-- ' if last else '|-- '}{label}"
                     + (f"    # {note}" if note else ""))
        if is_dir:
            lines += tree(root, prefix + ("    " if last else "|   "), child_rel)
    return lines



def main() -> int:
    p = argparse.ArgumentParser(prog="graphic_figure.py", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--json", action="store_true")

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--json", action="store_true",
                        default=argparse.SUPPRESS)

    sub = p.add_subparsers(dest="cmd", required=True)

    st = sub.add_parser("status", parents=[common],
                        help="every PowerPoint panel, and which renders are stale")
    st.add_argument("path")

    ad = sub.add_parser("add", parents=[common],
                        help="add a PowerPoint panel source to a figure folder")
    ad.add_argument("path")
    ad.add_argument("--figure", type=int, required=True,
                    help="the figure number, as in plan/figures/Fig02/")
    ad.add_argument("--panel", default="",
                    help="panel letter (A, B, ...); omit for a figure that is "
                         "one graphic with no panels")
    ad.add_argument("--supplementary", action="store_true")
    ad.add_argument("--width", default="single",
                    help="single | double | half | inches (default single)")
    ad.add_argument("--aspect", type=float, default=DEFAULT_ASPECT,
                    help="height / width (default 0.75)")
    ad.add_argument("--dry-run", action="store_true")

    rn = sub.add_parser("render", parents=[common],
                        help="render the panel sources without a full pipeline run")
    rn.add_argument("path")
    rn.add_argument("--figure", type=int, default=None)
    rn.add_argument("--supplementary", action="store_true")
    rn.add_argument("--force", action="store_true",
                    help="re-render even when the .pptx has not changed")
    rn.add_argument("--allow-overlap", action="store_true",
                    help="render even though elements of the drawing collide "
                         "(item 103). The override is recorded in the result")

    gm = sub.add_parser("geometry", parents=[common],
                        help="does the drawing collide with itself - a leader "
                             "line through a label, two labels on top of each "
                             "other (item 103)")
    gm.add_argument("path")
    gm.add_argument("--figure", type=int, default=None)
    gm.add_argument("--supplementary", action="store_true")

    args = p.parse_args()
    if not os.path.isdir(args.path):
        print(f"No such directory: {args.path}", file=sys.stderr)
        return 1

    if args.cmd == "status":
        res, printer = status(args.path), print_status
    elif args.cmd == "add":
        res = add(args.path, args.figure, panel=args.panel, width=args.width,
                  aspect=args.aspect, supplementary=args.supplementary,
                  dry_run=args.dry_run)
        printer = print_add
    elif args.cmd == "geometry":
        res = geometry(args.path, args.figure,
                       supplementary=args.supplementary)
        printer = print_geometry
    else:
        res = render(args.path, args.figure, force=args.force,
                     supplementary=args.supplementary,
                     allow_overlap=args.allow_overlap)
        printer = print_render

    if getattr(args, "json", False):
        print(json.dumps(res, indent=2, ensure_ascii=False))
    else:
        printer(res)
    if res.get("error"):
        return 1
    # A collision is a finding, and a finding exits 1 - the convention every
    # engine here follows. A check that could not run exits 2, because
    # "refused or unusable input" is what an absent python-pptx is, and
    # because 0 would be this command reporting a clean slide it never read.
    if args.cmd == "geometry":
        if not res.get("ran"):
            return 2
        return 1 if res.get("collisions") else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())

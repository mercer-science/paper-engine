#!/usr/bin/env python3
"""
graphic_figure.py - PowerPoint panel art inside a figure folder.

Some figure panels are not plots. A reaction scheme, an apparatus diagram, a
mechanism, a sample-preparation flow - nobody draws those in ggplot, and the
honest answer is not a drawing API but the editing surface people already
have. So a graphic panel is ONE PowerPoint slide, authored by you, rendered to
.png at the journal's pixel size, and composed into the figure by the same
script that draws the plotted panels beside it.

The layout, inside a float folder that tools/scaffold.py already made:

    plan/figures/Fig02/
        panels.R              GENERATED - renders every *_source.pptx
        figure.R              yours - composes the panels into the figure
        panelA_source.pptx    YOURS - open it in PowerPoint
        panelA_source.png     GENERATED
        .render_state.json    GENERATED - the SHA-256 that answers "stale?"
        figure.png/.pdf       GENERATED by save_float()

A whole-figure graphic (no panels at all) is `figure_source.pptx` instead.

The .pptx is written ONCE and never overwritten. It is the file you edit, and
an engine that regenerates it would throw away the work every time it ran.

Nothing here has to know whether the other panels are graphics. `image_panel()`
draws a dashed placeholder for art that does not exist yet, and a plotted panel
is an ordinary ggplot - so a figure can mix them freely, and can start as all
placeholders while the data is still being collected.

Usage:
  python graphic_figure.py status "path/to/Project"
  python graphic_figure.py add "path/to/Project" --figure 2 --panel A
  python graphic_figure.py add "path/to/Project" --figure 2          # whole figure
  python graphic_figure.py render "path/to/Project" [--figure 2] [--force]
"""


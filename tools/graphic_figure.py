def print_status(res: dict) -> None:
    if not res["floats"]:
        print("No PowerPoint panel art in this project yet.")
        print("  add some with: python tools/graphic_figure.py add "
              "<project> --figure 1 --panel A")
        return
    for fl in res["floats"]:
        print(f"{fl['label']:<12} {fl['dir']}")
        if not fl["has_panels_script"]:
            print(f"    no {PANELS_SCRIPT} - re-run `add` to write one")
        for s in fl["sources"]:
            if not s["rendered"]:
                state = "NOT RENDERED"
            elif s["stale"]:
                state = "STALE - the .pptx has changed"
            else:
                px = "x".join(str(v) for v in s["px"]) if s["px"] else ""
                state = f"current  {px}  via {s['backend']}"
            label = f"panel {s['panel']}" if s["panel"] else "whole figure"
            print(f"    {label:<14} {s['source']:<24} {state}")
    print()
    if res["backend"]:
        print(f"render backend on this machine: {res['backend']}")
    else:
        print("NO RENDER BACKEND on this machine - neither PowerPoint nor")
        print("  LibreOffice. Export each slide by hand (File > Save As, PNG)")
        print("  next to its .pptx; everything downstream is identical.")
    if res["stale"]:
        print(f"{res['stale']} source(s) need re-rendering: "
              f"Rscript plan/render_all.R")


def print_add(res: dict) -> None:
    if res.get("error"):
        print(res["error"])
        return
    verb = "Would create" if res["dry_run"] else "Created"
    print(f"{verb} {res['pptx']}")
    print(f"  {res['width_in']} x {res['height_in']} in  (the pixel size is "
          f"set at render time, from the journal's dpi)")
    print(f"  {res['panels_script']}   renders it, and render_all.R runs that "
          f"before figure.R")
    if res["figure_written"]:
        print(f"  {res['dir']}/figure.R   written to compose it "
              f"(the slot was still empty)")
    else:
        print(f"  {res['dir']}/figure.R   left alone - add this line yourself:")
        for line in res["compose_line"].splitlines():
            print(f"      {line}")
    print()
    print("Next:")
    print(f"  1. open {res['pptx']} in PowerPoint and draw the panel")
    print( "     (the slide is already the right size - do not resize it)")
    print( "  2. Rscript plan/render_all.R")
    print( "  3. open plan/preview.html")


def print_geometry(res: dict) -> None:
    if not res["ran"]:
        print("DID NOT RUN: " + res["note"])
        if not res["sources"]:
            return
    n = sum(1 for x in res["sources"] if x["read"])
    print(f"{res['path']}")
    print(f"  {n} drawn source(s) read")
    for x in res["sources"]:
        if not x["read"]:
            print(f"  COULD NOT READ  {x['source']}: {x['why']}")
            continue
        print(f"  {x['source']:<44} {x['labels']:>3} labels "
              f"{x['lines']:>3} lines")
    if not res["collisions"]:
        if res["ran"]:
            print("\nNo element collides with another. This is a statement "
                  "about geometry")
            print("only - it says nothing about whether the figure shows what "
                  "the caption claims.")
        return
    print(f"\n{len(res['collisions'])} COLLISION(S) - the drawing overlaps "
          f"itself:")
    for c in res["collisions"]:
        print(f"\n  {c['source']}  [{c['kind']}]")
        print(f"    {c['a']}")
        print(f"    {c['b']}")
        print(f"    {c['detail']}")
    print("\nA line through a word renders perfectly and is unreadable. "
          "Move one of the two")
    print("in PowerPoint, or pass --allow-overlap if this is deliberate.")


def print_render(res: dict) -> None:
    if res.get("error"):
        print(res["error"])
        return
    for d in res["rendered"]:
        print(f"{d['label']:<12} {d['dir']}  {'ok' if d['ok'] else 'FAILED'}")
        for line in (d["output"] or "").splitlines():
            if line.strip():
                print(f"    {line}")
        for s in d["sources"]:
            mark = "stale" if s["stale"] else "current"
            print(f"    {s['source']:<24} {mark}")



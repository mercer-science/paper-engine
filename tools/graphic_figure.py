def _load(name: str, filename: str):
    """Import a sibling engine by path under a distinct module name.

    tools/ and tests/ carry same-named files, so a plain import resolves to
    whichever directory is first on sys.path. Every suite in this toolkit
    loads its engine this way; doing the same here keeps `graphic_figure.py`
    importable from a test that is also called graphic_figure.py.
    """
    spec = importlib.util.spec_from_file_location(name,
                                                  os.path.join(HERE, filename))
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {filename}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod



PANELS_R = '''# {folder}/panels.R
# --- drawn float (create-graphic-figure) ---
# GENERATED by tools/graphic_figure.py. Safe to re-generate; safe to edit.
#
# The marker above records that this float's art is DRAWN rather than
# plotted, where a later round can read it: `scaffold.py float lint` reports
# a float marked drawn that holds no PowerPoint source, because that is a
# picture nobody but an R programmer can change (item 82). Repeated here
# rather than imported - every engine in this toolkit is standalone - and
# pinned against scaffold.py's own constant by tests/graphic_figure.py.
#
# Renders every *_source.pptx in this folder to a .png beside it, at the
# journal's pixel size. Unchanged sources are skipped - a SHA-256 of the
# .pptx answers "is the render stale", never the modification time, because
# OneDrive rewrites mtimes on sync.
#
# plan/render_all.R runs this BEFORE figure.R. That ordering is the whole
# reason the file is separate: the panel art has to exist before the script
# that composes it reads it, and "sorted order" alone would put figure.R
# first. See render_all.R's LAST_IN_FOLDER.
#
# You do not run this by hand. `Rscript plan/render_all.R` is still the only
# command. To force a re-render of everything here:
#     render_panel_sources(force = TRUE)

source(here::here("plan", "setup.R"))

render_panel_sources()
'''


def write_panels_script(float_path: str) -> str:
    path = os.path.join(float_path, PANELS_SCRIPT)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(PANELS_R.format(folder=os.path.basename(float_path)))
    return path


# ---------------------------------------------------------------------------
# figure.R
# ---------------------------------------------------------------------------

def compose_line(source: str) -> str:
    """The line that puts this panel's art into figure.R.

    graphic_panel() rather than image_panel() for the reason helpers.R gives:
    an aspect-locked image ignores the height patchwork hands it, so a title
    drawn inside the panel floats over whatever is beside it. Measured - two
    graphic panels side by side came out titled "Reaction sccAhpepmaeratus".
    """
    letter = panel_letter(source)
    stem = source[:-5]
    if not letter:
        return f'p <- graphic_panel("{stem}.png")'
    return (f'p_{letter.lower()} <- graphic_panel("{stem}.png",\n'
            f'                      title = "[TK: short panel title]", '
            f'tag = "{letter}")')


STARTER_FIGURE_R = '''# {folder}/figure.R
#
# A figure with PowerPoint panel art in it. panels.R has already turned every
# *_source.pptx in this folder into a .png by the time this runs - that is
# what render_all.R's ordering rule is for.
#
# Panels do not all have to be graphics. image_panel() draws a dashed grey
# placeholder when its .png is not there yet, and a plotted panel is an
# ordinary ggplot, so this figure renders from the first day and fills in as
# the art and the data arrive.

source(here::here("plan", "setup.R"))

# --- graphic panels ---------------------------------------------------------
{graphics}

# --- plotted panels ---------------------------------------------------------
# d <- load_data("data/raw/<file>.csv")
# p_{next_letter_lower} <- panel_title(
#   ggplot(d, aes(x = <x>, y = <y>)) + geom_point(size = 1.6) +
#     labs(x = "<x label>", y = "<y label>"),
#   title = "[TK: short panel title]", tag = "{next_letter}")

# --- composition ------------------------------------------------------------
# patchwork: `|` side by side, `/` stacked, and `(a | b) / c` for two rows.
#
# State `height =` as soon as the layout is more than one row. save_float()
# derives a height from the panel COUNT, which assumes a single row - three
# panels arranged (A | B) / C come out at the height of one row and the
# graphic panels shrink to nothing in the middle of it.
{compose}
'''


def is_pristine_slot(float_path: str, script: str) -> bool:
    """Is this float folder still exactly what the scaffold put there?

    True only when it holds that one script and the script is byte-identical
    to the template. Anything else means somebody has worked in here, and a
    generator that rewrites their figure.R has destroyed the work it was
    called to help with.
    """
    try:
        contents = os.listdir(float_path)
    except OSError:
        return False
    if contents != [script]:
        return False
    sub = "figures" if script == "figure.R" else "tables"
    tmpl = os.path.join(TEMPLATE_DIR, "plan", sub, "_template", script)
    try:
        with open(os.path.join(float_path, script), encoding="utf-8") as a, \
                open(tmpl, encoding="utf-8") as b:
            return a.read() == b.read()
    except OSError:
        return False


def starter_figure(float_path: str, sources: list[str]) -> str:
    letters = [panel_letter(s) for s in sources if panel_letter(s)]
    nxt = chr(ord(max(letters)) + 1) if letters else "B"
    graphics = "\n".join(compose_line(s) for s in sources) or "# (none yet)"
    if letters:
        compose = ("p <- " + " | ".join(f"p_{l.lower()}" for l in letters)
                   + "\nsave_float(p)")
    else:
        compose = "save_float(p)"
    return STARTER_FIGURE_R.format(
        folder=os.path.basename(float_path), graphics=graphics,
        compose=compose, next_letter=nxt, next_letter_lower=nxt.lower())



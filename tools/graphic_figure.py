SOURCE_RE = re.compile(r"^(?:panel[A-Z]|figure)_source\.pptx$")


# ---------------------------------------------------------------------------
# Geometry
# ---------------------------------------------------------------------------
# A graphic panel's absolute size matters less than it looks: image_panel()
# preserves the .png's aspect ratio and fits it into whatever slot patchwork
# gives it. What the size DOES decide is how many pixels the panel has, and a
# panel authored at 1.6 in and printed at 3.3 in is soft in exactly the way a
# reviewer notices. So the default is a full single column, and the shape is
# the dial worth turning.

WIDTHS = {"single": 3.33, "double": 7.0, "half": 1.65}
DEFAULT_ASPECT = 0.75

# THE PIXEL COUNT IS NOT DECIDED HERE. plan/theme/render_pptx.R multiplies the
# slide's inches by DPI, and DPI comes from theme_journal.R's preset table as
# overridden by a sourced plan/theme/journal_target.yml - a resolution this
# engine cannot reproduce, because a journal_target.yml written from the
# journal's own guidelines beats any table shipped in Python.
#
# So a dpi table here would be a second copy that disagrees with the first, and
# it did: `add` reported 999 x 749 px for a panel that rendered at 1998 x 1499.
# What this engine fixes is the slide's INCHES, which is what decides the
# aspect ratio; `status` reports the pixel size the render actually produced,
# read back out of .render_state.json rather than predicted.


def read_project_yml(root: str) -> dict:
    return _scaffold.read_project_yml(root)


def panel_spec(root: str, width: str = "single",
               aspect: float = DEFAULT_ASPECT) -> dict:
    """The spec toc_graphic.write_pptx() wants, for a figure panel."""
    try:
        w = float(width)
    except (TypeError, ValueError):
        w = WIDTHS.get(str(width).lower(), WIDTHS["single"])
    return {"term": "figure panel", "width_in": round(w, 3),
            "height_in": round(w * float(aspect), 3),
            "font_family": "Arial", "font_preferred_pt": 8, "font_min_pt": 6}


# ---------------------------------------------------------------------------
# Locating a float and its sources
# ---------------------------------------------------------------------------

def find_float(root: str, number: int, supplementary: bool = False,
               kind: str = "figure") -> dict | None:
    for f in list_float_dirs(root):
        if (f["kind"] == kind and f["n"] == number
                and f["supplementary"] == supplementary):
            return f
    return None


def sources_in(path: str) -> list[str]:
    """Every panel source in a float folder, in panel order.

    PowerPoint writes ~$name.pptx beside a file it has open; that lock stub is
    not a source, and rendering it produces a blank slide rather than an error
    - which is the worst of the three outcomes, because a blank panel looks
    like a panel.
    """
    try:
        names = sorted(os.listdir(path))
    except OSError:
        return []
    return [n for n in names
            if SOURCE_RE.match(n) and not n.startswith("~$")]


def panel_letter(source: str) -> str:
    m = PANEL_RE.match(source)
    return m.group(1) if m else ""


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    try:
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(65536), b""):
                h.update(chunk)
    except OSError:
        return ""
    return h.hexdigest()


def read_state(path: str) -> dict:
    try:
        with open(os.path.join(path, STATE_FILE), "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return {}


def source_state(float_path: str, source: str) -> dict:
    """Is this source's .png current? Answered by content, never by mtime.

    OneDrive rewrites modification times on sync, so an mtime comparison both
    re-renders files nobody touched and can call a file current after a sync
    has replaced it. The digest is the same one plan/theme/render_pptx.R
    writes, so the R side and this side cannot disagree about what is stale.
    """
    pptx = os.path.join(float_path, source)
    png = os.path.join(float_path, source[:-5] + ".png")
    rec = read_state(float_path).get(source, {})
    have = os.path.isfile(png)
    digest = _sha256(pptx)
    return {"source": source, "panel": panel_letter(source),
            "pptx": pptx, "png": png, "rendered": have,
            "stale": (not have) or rec.get("sha256") != digest,
            "backend": rec.get("backend", ""),
            "px": rec.get("px", [])}



def status(root: str) -> dict:
    floats = []
    for f in list_float_dirs(root):
        srcs = sources_in(f["path"])
        if not srcs:
            continue
        floats.append({
            "label": f["label"], "dir": f["rel"],
            "has_panels_script": os.path.isfile(
                os.path.join(f["path"], PANELS_SCRIPT)),
            "sources": [source_state(f["path"], s) for s in srcs]})
    return {"path": os.path.abspath(root), "floats": floats,
            "backend": detect_backend(),
            "stale": sum(1 for fl in floats for s in fl["sources"]
                         if s["stale"])}


def detect_backend() -> str:
    """Which renderer this machine actually has, checked rather than assumed."""
    import glob
    if glob.glob("C:/Program Files/Microsoft Office/root/Office*/POWERPNT.EXE") \
            or glob.glob("C:/Program Files (x86)/Microsoft Office/root/"
                         "Office*/POWERPNT.EXE") \
            or glob.glob("C:/Program Files/Microsoft Office/Office*/POWERPNT.EXE"):
        return "powerpoint-com"
    for c in ("C:/Program Files/LibreOffice/program/soffice.exe",
              "/usr/bin/soffice", "/usr/local/bin/soffice",
              "/Applications/LibreOffice.app/Contents/MacOS/soffice"):
        if os.path.exists(c):
            return "libreoffice"
    return ""


def add(root: str, number: int, panel: str = "", width: str = "single",
        aspect: float = DEFAULT_ASPECT, supplementary: bool = False,
        dry_run: bool = False) -> dict:
    """Add one PowerPoint panel source to a figure folder."""
    fl = find_float(root, number, supplementary)
    if fl is None:
        return {"error": f"no Figure {'S' if supplementary else ''}{number} in "
                         f"plan/figures/ - make one first with:\n"
                         f"  python tools/scaffold.py float new <project> --figure"
                         f"{' --supplementary' if supplementary else ''}"}

    panel = (panel or "").strip().upper()
    if panel and not re.fullmatch(r"[A-Z]", panel):
        return {"error": f"panel must be a single letter A-Z, not {panel!r}"}
    source = f"panel{panel}_source.pptx" if panel else "figure_source.pptx"
    existing = sources_in(fl["path"])

    # A whole-figure graphic and lettered panels are different shapes of
    # figure, and a folder holding both renders one of them into nothing.
    if panel and "figure_source.pptx" in existing:
        return {"error": f"{fl['rel']} already has a whole-figure "
                         f"figure_source.pptx. Rename it to panelA_source.pptx "
                         f"first if this figure is becoming multi-panel."}
    if not panel and any(PANEL_RE.match(e) for e in existing):
        return {"error": f"{fl['rel']} already has lettered panels "
                         f"({', '.join(existing)}). Pass --panel to add another."}

    target = os.path.join(fl["path"], source)
    if os.path.exists(target):
        # The .pptx is the editing surface. Regenerating it would throw away
        # the drawing, which is the only thing in the folder nothing else can
        # reproduce.
        return {"error": f"{fl['rel']}/{source} already exists, and it is "
                         f"yours - this never overwrites one. Open it in "
                         f"PowerPoint, or delete it first to start over."}

    spec = panel_spec(root, width, aspect)
    suggestion = {
        "title": "[TK: what this panel shows]",
        "stages": [
            {"label": "[TK: starting point]", "caption": ""},
            {"label": "[TK: what happens]", "caption": ""},
        ],
        "footnote": "",
    }
    # Asked BEFORE anything is written into the folder: is_pristine_slot()
    # answers "does this folder hold only the untouched template", and writing
    # panels.R first makes the answer permanently no. That is how a generator
    # ends up never writing the starter figure.R it exists to write.
    pristine = is_pristine_slot(fl["path"], "figure.R")

    written = {"shapes": 0}
    if not dry_run:
        written = _toc.write_pptx(target, spec, suggestion)
        write_panels_script(fl["path"])

    figure_r = os.path.join(fl["path"], "figure.R")
    sources_after = sorted(set(existing) | {source})
    if pristine and not dry_run:
        with open(figure_r, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(starter_figure(fl["path"], sources_after))

    return {"path": os.path.abspath(root), "label": fl["label"],
            "dir": fl["rel"], "source": source,
            "pptx": f"{fl['rel']}/{source}",
            "png": f"{fl['rel']}/{source[:-5]}.png",
            "panels_script": f"{fl['rel']}/{PANELS_SCRIPT}",
            "figure_written": pristine,
            "compose_line": compose_line(source),
            "width_in": spec["width_in"], "height_in": spec["height_in"],
            "shapes": written.get("shapes", 0), "dry_run": dry_run}


def _rscript() -> str | None:
    return _toc._rscript()


# ---------------------------------------------------------------------------
# Geometry - does the drawing collide with itself? (item 103)
# ---------------------------------------------------------------------------
#
# A drawn float is authored as a PowerPoint slide and rendered to an image,
# and nothing anywhere checked that the slide's own elements do not collide.
# A leader line running from a marker to its label can pass straight through a
# DIFFERENT label's text, and two labels can sit on top of each other, and the
# render still succeeds: the .png is written, the staleness record is written,
# the float is composed into the manuscript, and no command reports anything.
#
# Measured: Figure 1 of a real review drew two cytoplasmic-tail leader lines
# straight through the words S-palmitoylation and ubiquitination, so both
# labels had a vertical rule through the middle of them. It rendered, embedded
# at the right size and shipped with no complaint. The user caught it by
# looking at the picture - which is exactly the reading that gets skipped once
# a figure has been carried unchanged through a round or two.
#
# So legibility of a drawn float was asserted by nobody, while every other
# property of it was machine-checked. This is the check, and it lives where
# the float is PRODUCED rather than with a later reader of the .png, because
# it needs the label boxes and the line endpoints and the .png has only
# pixels.
#
# **A leader line is SUPPOSED to touch its own label.** That is the false
# positive that would make this check worthless, and it is why the rule is
# not "no line touches any label". A line's own labels are the ones its two
# endpoints land in or beside; a crossing is the line passing through some
# OTHER label. That is the shape of the real defect and it is the shape this
# tests for.

# python-pptx, and it may not be installed. Absent, this reports DID NOT RUN
# and says so out loud - it never reports a clean slide it did not read. A
# check that cannot run and stays quiet is worse than no check, because the
# silence is indistinguishable from a pass (items 80 and 114).
EMU_PER_INCH = 914400

# A label's ink does not reach the edge of its text frame, and a leader line
# is routinely drawn to stop just inside it. Both boxes are shrunk towards
# their centres before anything is compared, so touching an edge is not a
# collision and crossing the middle of a word is.
INK_MARGIN = 0.18

# Two labels overlapping by less than this fraction of the smaller one is
# kerning, not a collision.
OVERLAP_TOLERANCE = 0.06


def _shrink(box: tuple, frac: float = INK_MARGIN) -> tuple:
    x0, y0, x1, y1 = box
    dx, dy = (x1 - x0) * frac, (y1 - y0) * frac
    return (x0 + dx, y0 + dy, x1 - dx, y1 - dy)


def _seg_hits_box(p0: tuple, p1: tuple, box: tuple) -> bool:
    """Liang-Barsky: does the segment p0->p1 enter this rectangle?"""
    x0, y0 = p0
    x1, y1 = p1
    bx0, by0, bx1, by1 = box
    dx, dy = x1 - x0, y1 - y0
    t0, t1 = 0.0, 1.0
    for p, q in ((-dx, x0 - bx0), (dx, bx1 - x0),
                 (-dy, y0 - by0), (dy, by1 - y0)):
        if p == 0:
            if q < 0:
                return False
            continue
        r = q / p
        if p < 0:
            if r > t1:
                return False
            t0 = max(t0, r)
        else:
            if r < t0:
                return False
            t1 = min(t1, r)
    return t0 <= t1


def _overlap_fraction(a: tuple, b: tuple) -> float:
    ax0, ay0, ax1, ay1 = a
    bx0, by0, bx1, by1 = b
    w = min(ax1, bx1) - max(ax0, bx0)
    h = min(ay1, by1) - max(ay0, by0)
    if w <= 0 or h <= 0:
        return 0.0
    smaller = min((ax1 - ax0) * (ay1 - ay0), (bx1 - bx0) * (by1 - by0))
    return (w * h) / smaller if smaller else 0.0


def _slide_elements(path: str) -> dict:
    """Every label box and every line segment on the first slide.

    Returns `{"labels": [...], "lines": [...]}` or raises. A shape is a LABEL
    when it carries text and a LINE when it does not and is a connector or a
    straight-line autoshape. Anything else - a picture, a filled block, a
    shape with neither - is neither, and is ignored rather than guessed at.
    """
    from pptx import Presentation                      # noqa: PLC0415

    prs = Presentation(path)
    slide = prs.slides[0]
    labels, lines = [], []
    for sh in slide.shapes:
        try:
            left, top = int(sh.left or 0), int(sh.top or 0)
            wid, hgt = int(sh.width or 0), int(sh.height or 0)
        except (TypeError, ValueError):
            continue
        # Asked through getattr in both halves. `has_text_frame` is False on
        # a picture or a connector and `text_frame` does not exist on the
        # base shape at all, so reaching for the attribute directly is an
        # AttributeError on exactly the shapes this walks past.
        text = ""
        frame = getattr(sh, "text_frame", None) \
            if getattr(sh, "has_text_frame", False) else None
        if frame is not None:
            text = (getattr(frame, "text", "") or "").strip()
        box = (float(left), float(top), float(left + wid), float(top + hgt))
        if text:
            labels.append({"name": sh.name, "text": " ".join(text.split()),
                           "box": box})
            continue
        # A connector carries its own direction through flipH / flipV; a plain
        # line autoshape is the box diagonal. Reading the flips is what stops
        # every line being read as top-left to bottom-right.
        flip_h = flip_v = False
        try:
            xfrm = sh._element.spPr.xfrm                # noqa: SLF001
            flip_h = bool(xfrm is not None and xfrm.get("flipH") == "1")
            flip_v = bool(xfrm is not None and xfrm.get("flipV") == "1")
        except AttributeError:
            pass
        if wid == 0 and hgt == 0:
            continue
        x0 = box[2] if flip_h else box[0]
        x1 = box[0] if flip_h else box[2]
        y0 = box[3] if flip_v else box[1]
        y1 = box[1] if flip_v else box[3]
        lines.append({"name": sh.name, "p0": (x0, y0), "p1": (x1, y1)})
    return {"labels": labels, "lines": lines}


def geometry(path: str, number: int | None = None,
             supplementary: bool = False) -> dict:
    """Every drawn source in this project, or one figure's, checked for
    collisions between its own elements.

    Reports `ok`, `collisions`, and - when python-pptx is not installed -
    `ran: false` with the reason. It never reports a clean slide it could not
    read.
    """
    out: dict = {"path": os.path.abspath(path), "ran": True, "note": "",
                 "sources": [], "collisions": [], "ok": True}
    # Asked rather than imported. The import itself happens in
    # `_slide_elements`, where it is used; importing here only to find out
    # whether it exists is the unused import a linter is right about.
    if importlib.util.find_spec("pptx") is None:
        out["ran"] = False
        out["note"] = ("python-pptx is not installed, so the slide's own "
                       "geometry was NOT checked. `pip install python-pptx`. "
                       "This is DID NOT RUN, not a clean result.")
        return out

    for f in list_float_dirs(path):
        if number is not None and not (f["n"] == number
                                       and f["supplementary"] == supplementary
                                       and f["kind"] == "figure"):
            continue
        for src in sources_in(f["path"]):
            full = os.path.join(f["path"], src)
            try:
                el = _slide_elements(full)
            except Exception as exc:
                out["sources"].append({"source": os.path.join(f["rel"], src),
                                       "read": False, "why": str(exc),
                                       "labels": 0, "lines": 0})
                out["ran"] = False
                out["note"] = ("at least one source could not be read, so "
                               "this is not a clean result")
                continue
            labels, lines = el["labels"], el["lines"]
            out["sources"].append({"source": os.path.join(f["rel"], src),
                                   "read": True, "why": "",
                                   "labels": len(labels), "lines": len(lines)})

            # --- a leader line through somebody else's label --------------
            for ln in lines:
                own = set()
                for i, lab in enumerate(labels):
                    grown = _shrink(lab["box"], -0.25)
                    for pt in (ln["p0"], ln["p1"]):
                        if (grown[0] <= pt[0] <= grown[2]
                                and grown[1] <= pt[1] <= grown[3]):
                            own.add(i)
                for i, lab in enumerate(labels):
                    if i in own:
                        continue
                    if _seg_hits_box(ln["p0"], ln["p1"], _shrink(lab["box"])):
                        out["collisions"].append({
                            "source": os.path.join(f["rel"], src),
                            "kind": "leader_through_label",
                            "a": ln["name"],
                            "b": "%s (%s)" % (lab["name"], lab["text"][:40]),
                            "detail": ("a leader line runs through the words "
                                       "of a label it does not belong to")})

            # --- two labels on top of each other --------------------------
            for i in range(len(labels)):
                for j in range(i + 1, len(labels)):
                    frac = _overlap_fraction(_shrink(labels[i]["box"]),
                                             _shrink(labels[j]["box"]))
                    if frac > OVERLAP_TOLERANCE:
                        out["collisions"].append({
                            "source": os.path.join(f["rel"], src),
                            "kind": "labels_overlap",
                            "a": "%s (%s)" % (labels[i]["name"],
                                              labels[i]["text"][:40]),
                            "b": "%s (%s)" % (labels[j]["name"],
                                              labels[j]["text"][:40]),
                            "detail": "%d%% of the smaller label is covered"
                                      % round(frac * 100)})
    out["ok"] = not out["collisions"]
    return out


def render(root: str, number: int | None = None, force: bool = False,
           supplementary: bool = False, timeout: int = 240,
           allow_overlap: bool = False) -> dict:
    """Render the panel sources without going through the whole R pipeline."""
    rs = _rscript()
    if not rs:
        return {"error": "Rscript not found on PATH or under C:/Program Files/R"}
    targets = []
    for f in list_float_dirs(root):
        if number is not None and not (f["n"] == number
                                       and f["supplementary"] == supplementary
                                       and f["kind"] == "figure"):
            continue
        if sources_in(f["path"]):
            targets.append(f)
    if not targets:
        return {"error": "no float folder here holds a *_source.pptx"}

    # Item 103, and it runs BEFORE the render rather than after it. A .png
    # that exists is a .png something composes into the manuscript, and the
    # staleness record written beside it says the panel is current. Refusing
    # afterwards would leave both on disk.
    geo = geometry(root, number, supplementary)
    if geo["collisions"] and not allow_overlap:
        return {"path": os.path.abspath(root), "rendered": [], "ok": False,
                "geometry": geo,
                "error": ("%d collision(s) in the drawing itself - nothing "
                          "was rendered. A line through a word renders "
                          "perfectly and is unreadable, so this refuses "
                          "rather than writing it. `--allow-overlap` "
                          "overrides, and says so in the result."
                          % len(geo["collisions"]))}

    done = []
    for f in targets:
        script = os.path.join(f["path"], PANELS_SCRIPT)
        if not os.path.isfile(script):
            write_panels_script(f["path"])
        # Sourced through setup.R exactly as render_all.R would, and with the
        # float context set the same way - so a render driven from here and a
        # render driven from the pipeline cannot behave differently.
        code = (f'source(here::here("plan","setup.R"));'
                f'set_float_context({_r_str(f["path"])}, {_r_str(f["label"])});'
                f'render_panel_sources(force={"TRUE" if force else "FALSE"})')
        p = subprocess.run([rs, "-e", code], cwd=root, capture_output=True,
                           text=True, encoding="utf-8", errors="replace",
                           timeout=timeout)
        out = (p.stdout or "") + (p.stderr or "")
        done.append({"label": f["label"], "dir": f["rel"],
                     "ok": p.returncode == 0, "output": out.strip(),
                     "sources": [source_state(f["path"], s)
                                 for s in sources_in(f["path"])]})
    return {"path": os.path.abspath(root), "rendered": done,
            "geometry": geo,
            "ok": all(d["ok"] for d in done)}


def _r_str(s: str) -> str:
    return '"' + s.replace("\\", "/").replace('"', '\\"') + '"'


